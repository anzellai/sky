//go:build !js

package rt

import (
	"crypto/sha256"
	"encoding/hex"
	"flag"
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"strings"
	"testing"
)

// spa_boot_brotli.go holds SpaBootJS compressed with brotli, built ahead of time
// because the Go standard library has no brotli encoder. This test keeps it in
// step with SpaBootJS: it fails when SpaBootJS changed and the brotli form was
// not rebuilt, and when the brotli bytes do not decode to SpaBootJS.
//
// Rebuild it (Node.js's zlib compresses; quality 11, text mode):
//
//	cd runtime-go && go test ./rt -run TestSpaBootBrotliIsCurrent -args -bless-spa-boot-brotli

var blessSpaBootBrotli = flag.Bool("bless-spa-boot-brotli", false,
	"rewrite rt/spa_boot_brotli.go from the current SpaBootJS")

const spaBootBrotliRebuild = "cd runtime-go && go test ./rt -run TestSpaBootBrotliIsCurrent -args -bless-spa-boot-brotli"

func TestSpaBootBrotliIsCurrent(t *testing.T) {
	sum := sha256.Sum256([]byte(SpaBootJS))
	want := hex.EncodeToString(sum[:])
	if *blessSpaBootBrotli {
		writeSpaBootBrotli(t, want)
		return
	}
	if spaBootBrotliOf != want {
		t.Fatalf("rt/spa_boot_brotli.go was compressed from another SpaBootJS (sha256 %q, the current one is %q), "+
			"so the boot loader is served without brotli. Rebuild it: %s", spaBootBrotliOf, want, spaBootBrotliRebuild)
	}
	if got := brotliDecode(t, []byte(spaBootBrotli)); got != SpaBootJS {
		t.Fatalf("rt/spa_boot_brotli.go does not decode to SpaBootJS (%d bytes, want %d). Rebuild it: %s",
			len(got), len(SpaBootJS), spaBootBrotliRebuild)
	}
	if spaBootBrotliBody() != spaBootBrotli {
		t.Fatal("spaBootBrotliBody refused a current brotli form")
	}
}

// writeSpaBootBrotli compresses SpaBootJS with Node.js's zlib and writes
// spa_boot_brotli.go.
func writeSpaBootBrotli(t *testing.T, sum string) {
	t.Helper()
	node := requireNode(t)
	dir := t.TempDir()
	in := filepath.Join(dir, "spa-boot.js")
	if err := os.WriteFile(in, []byte(SpaBootJS), 0o600); err != nil {
		t.Fatal(err)
	}
	out, err := exec.Command(node, "-e", `const z = require("zlib");
const src = require("fs").readFileSync(process.argv[1]);
process.stdout.write(z.brotliCompressSync(src, { params: {
  [z.constants.BROTLI_PARAM_QUALITY]: 11,
  [z.constants.BROTLI_PARAM_MODE]: z.constants.BROTLI_MODE_TEXT,
  [z.constants.BROTLI_PARAM_SIZE_HINT]: src.length,
} }));`, in).Output()
	if err != nil {
		t.Fatalf("node brotli compress: %v", err)
	}
	var b strings.Builder
	b.WriteString("// Code generated by `go test ./rt -run TestSpaBootBrotliIsCurrent -args -bless-spa-boot-brotli`; DO NOT EDIT.\n\n")
	b.WriteString("//go:build !js\n\npackage rt\n\n")
	b.WriteString("// spaBootBrotliOf is the SHA-256 of the SpaBootJS that spaBootBrotli was\n")
	b.WriteString("// compressed from. spaBootBrotliBody sends no brotli when it differs.\n")
	fmt.Fprintf(&b, "const spaBootBrotliOf = %q\n\n", sum)
	fmt.Fprintf(&b, "// spaBootBrotli is SpaBootJS compressed with brotli (quality 11, text mode),\n")
	fmt.Fprintf(&b, "// %d bytes for a %d-byte script.\n", len(out), len(SpaBootJS))
	b.WriteString("const spaBootBrotli = \"\" +\n")
	const per = 32
	for i := 0; i < len(out); i += per {
		end := min(i+per, len(out))
		b.WriteString("\t\"")
		for _, c := range out[i:end] {
			fmt.Fprintf(&b, "\\x%02x", c)
		}
		b.WriteString("\"")
		if end < len(out) {
			b.WriteString(" +")
		}
		b.WriteString("\n")
	}
	if err := os.WriteFile("spa_boot_brotli.go", []byte(b.String()), 0o644); err != nil {
		t.Fatal(err)
	}
	t.Logf("wrote rt/spa_boot_brotli.go: %d brotli bytes for %d bytes of SpaBootJS", len(out), len(SpaBootJS))
}
