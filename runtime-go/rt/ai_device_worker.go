package rt

// ai_device_worker.go — the Web Worker that runs a Std.Ai.Device model in a
// browser.
//
// The worker is one same-origin script with no inline code and no eval, so it
// runs under the strict policy (`script-src 'self' 'wasm-unsafe-eval'`). The
// backend serves it from memory at AiDeviceWorkerPath (a content-hashed
// name), and `sky build` stages the same bytes into the frontend dist
// (rust/crates/sky/src/main.rs reads this constant; a drift test keeps the
// two equal).
//
// It loads the engine the build staged (`--ai-web-engine`: the WebGPU and
// CPU builds of sky_llama.cpp over llama.cpp, named in the page's
// `sky-ai-engine` meta), downloads a slot's model and adapter in 64 MiB Range
// chunks into the origin-private file system (OPFS), checks every chunk and
// the whole file against the server's SHA-256, and answers chat requests.
//
// Protocol: the page posts `{id, op, …}` and the worker answers
// `{id, ok, value}` or `{id, ok: false, error}`; a download also posts
// `{type: "progress", key, doneBytes, totalBytes}`. An error is
// `ai:<json>` for a typed Std.Ai failure (ai_device_proto.go) or
// `<kind>: <message>` like every native op.
//
// A WebGPU engine that registers no GPU device (a browser whose adapter has
// no shader-f16, or a software adapter) is DeviceUnsupported: the worker
// never lets the WebGPU build run on the CPU in silence.

// AiDeviceWorkerJS is the worker script.
const AiDeviceWorkerJS = `// Sky Std.Ai.Device worker. Generated by the Sky runtime; do not edit.
'use strict';
const CHUNK = 64 * 1024 * 1024;
const MAX_BROWSER_MODEL = 1024 * 1024 * 1024;

function fail(code, message, attrs) {
  const e = new Error(message);
  e.sky = 'ai:' + JSON.stringify({ failure: { code, message, attrs: attrs || [] } });
  return e;
}
function unsupported(backend, reason) {
  return fail('DeviceUnsupported', reason, [['backend', backend], ['reason', reason]]);
}

// SHA-256 over a stream of chunks (the Web Crypto digest takes one buffer).
const K = new Uint32Array([
  0x428a2f98, 0x71374491, 0xb5c0fbcf, 0xe9b5dba5, 0x3956c25b, 0x59f111f1, 0x923f82a4, 0xab1c5ed5,
  0xd807aa98, 0x12835b01, 0x243185be, 0x550c7dc3, 0x72be5d74, 0x80deb1fe, 0x9bdc06a7, 0xc19bf174,
  0xe49b69c1, 0xefbe4786, 0x0fc19dc6, 0x240ca1cc, 0x2de92c6f, 0x4a7484aa, 0x5cb0a9dc, 0x76f988da,
  0x983e5152, 0xa831c66d, 0xb00327c8, 0xbf597fc7, 0xc6e00bf3, 0xd5a79147, 0x06ca6351, 0x14292967,
  0x27b70a85, 0x2e1b2138, 0x4d2c6dfc, 0x53380d13, 0x650a7354, 0x766a0abb, 0x81c2c92e, 0x92722c85,
  0xa2bfe8a1, 0xa81a664b, 0xc24b8b70, 0xc76c51a3, 0xd192e819, 0xd6990624, 0xf40e3585, 0x106aa070,
  0x19a4c116, 0x1e376c08, 0x2748774c, 0x34b0bcb5, 0x391c0cb3, 0x4ed8aa4a, 0x5b9cca4f, 0x682e6ff3,
  0x748f82ee, 0x78a5636f, 0x84c87814, 0x8cc70208, 0x90befffa, 0xa4506ceb, 0xbef9a3f7, 0xc67178f2]);
class Sha256 {
  constructor() {
    this.h = new Uint32Array([0x6a09e667, 0xbb67ae85, 0x3c6ef372, 0xa54ff53a, 0x510e527f, 0x9b05688c, 0x1f83d9ab, 0x5be0cd19]);
    this.buf = new Uint8Array(64); this.n = 0; this.len = 0; this.w = new Uint32Array(64);
  }
  block(b, o) {
    const w = this.w, h = this.h;
    for (let i = 0; i < 16; i++) w[i] = (b[o + 4 * i] << 24) | (b[o + 4 * i + 1] << 16) | (b[o + 4 * i + 2] << 8) | b[o + 4 * i + 3];
    for (let i = 16; i < 64; i++) {
      const x = w[i - 15], y = w[i - 2];
      const s0 = ((x >>> 7) | (x << 25)) ^ ((x >>> 18) | (x << 14)) ^ (x >>> 3);
      const s1 = ((y >>> 17) | (y << 15)) ^ ((y >>> 19) | (y << 13)) ^ (y >>> 10);
      w[i] = (w[i - 16] + s0 + w[i - 7] + s1) | 0;
    }
    let a = h[0], bb = h[1], c = h[2], d = h[3], e = h[4], f = h[5], g = h[6], hh = h[7];
    for (let i = 0; i < 64; i++) {
      const S1 = ((e >>> 6) | (e << 26)) ^ ((e >>> 11) | (e << 21)) ^ ((e >>> 25) | (e << 7));
      const ch = (e & f) ^ (~e & g);
      const t1 = (hh + S1 + ch + K[i] + w[i]) | 0;
      const S0 = ((a >>> 2) | (a << 30)) ^ ((a >>> 13) | (a << 19)) ^ ((a >>> 22) | (a << 10));
      const mj = (a & bb) ^ (a & c) ^ (bb & c);
      const t2 = (S0 + mj) | 0;
      hh = g; g = f; f = e; e = (d + t1) | 0; d = c; c = bb; bb = a; a = (t1 + t2) | 0;
    }
    h[0] += a; h[1] += bb; h[2] += c; h[3] += d; h[4] += e; h[5] += f; h[6] += g; h[7] += hh;
  }
  update(data) {
    let i = 0;
    this.len += data.length;
    if (this.n > 0) {
      while (this.n < 64 && i < data.length) this.buf[this.n++] = data[i++];
      if (this.n === 64) { this.block(this.buf, 0); this.n = 0; }
    }
    for (; i + 64 <= data.length; i += 64) this.block(data, i);
    while (i < data.length) this.buf[this.n++] = data[i++];
    return this;
  }
  hex() {
    const bits = this.len * 8;
    const pad = new Uint8Array(((this.n < 56) ? 56 : 120) - this.n + 8);
    pad[0] = 0x80;
    const hi = Math.floor(bits / 0x100000000), lo = bits >>> 0;
    const p = pad.length;
    pad[p - 8] = hi >>> 24; pad[p - 7] = hi >>> 16; pad[p - 6] = hi >>> 8; pad[p - 5] = hi;
    pad[p - 4] = lo >>> 24; pad[p - 3] = lo >>> 16; pad[p - 2] = lo >>> 8; pad[p - 1] = lo;
    this.update(pad);
    let out = '';
    for (const v of this.h) out += (v >>> 0).toString(16).padStart(8, '0');
    return out;
  }
}
async function digestHex(buf) {
  const d = await crypto.subtle.digest('SHA-256', buf);
  return Array.from(new Uint8Array(d), (b) => b.toString(16).padStart(2, '0')).join('');
}

// The device store: the origin-private file system. A browser without one,
// or one that refuses it (a private window), stores nothing: StorageDenied.
async function storeDir() {
  const denied = (why) => fail('StorageDenied', 'this browser keeps no device storage: ' + why, [['needBytes', '0'], ['availableBytes', '0']]);
  if (!navigator.storage || !navigator.storage.getDirectory) throw denied('no origin-private file system');
  try {
    const root = await navigator.storage.getDirectory();
    return await root.getDirectoryHandle('sky-ai', { create: true });
  } catch (e) {
    throw denied(String(e && e.message || e));
  }
}
// Whether the store accepts a write (a private window may list the store and
// refuse every write).
async function storeWritable() {
  try {
    const dir = await storeDir();
    const fh = await dir.getFileHandle('.probe', { create: true });
    await writeAt(fh, 0, new Uint8Array([1]));
    await dir.removeEntry('.probe');
    return true;
  } catch (e) { return false; }
}
async function exists(dir, name) {
  try { await dir.getFileHandle(name); return true; } catch (e) { return false; }
}
async function readyList() {
  try {
    const dir = await storeDir();
    const out = [];
    for await (const [name] of dir.entries()) {
      if (name.endsWith('.ok')) out.push(name.slice(0, -3));
    }
    return out;
  } catch (e) { return []; }
}

async function caps(engines) {
  const out = { platform: 'browser', backends: [], unsupported: [], storageAvailableBytes: 0, metered: false, ready: [], failed: [] };
  out.unsupported.push({ backend: 'native', reason: 'a browser has no native shell' });
  const jspi = typeof WebAssembly === 'object' && typeof WebAssembly.Suspending === 'function';
  if (!engines.webgpu) {
    out.unsupported.push({ backend: 'webgpu', reason: 'the build has no WebGPU engine (sky build --ai-web-engine webgpu)' });
  } else if (!jspi) {
    out.unsupported.push({ backend: 'webgpu', reason: 'this browser has no JavaScript Promise Integration' });
  } else if (!navigator.gpu) {
    out.unsupported.push({ backend: 'webgpu', reason: 'this browser has no WebGPU' });
  } else {
    let adapter = null;
    try { adapter = await navigator.gpu.requestAdapter(); } catch (e) { adapter = null; }
    if (!adapter) {
      out.unsupported.push({ backend: 'webgpu', reason: 'no WebGPU adapter' });
    } else if (!adapter.features.has('shader-f16')) {
      out.unsupported.push({ backend: 'webgpu', reason: 'the GPU has no shader-f16' });
    } else {
      out.backends.push({ backend: 'webgpu', maxModelBytes: MAX_BROWSER_MODEL });
    }
  }
  if (!engines.cpu) {
    out.unsupported.push({ backend: 'wasm-cpu', reason: 'the build has no CPU engine (sky build --ai-web-engine cpu)' });
  } else {
    out.backends.push({ backend: 'wasm-cpu', maxModelBytes: MAX_BROWSER_MODEL });
  }
  try {
    const est = await navigator.storage.estimate();
    out.storageAvailableBytes = Math.max(0, Math.floor((est.quota || 0) - (est.usage || 0)));
  } catch (e) { out.storageAvailableBytes = 0; }
  if (!(await storeWritable())) out.storageAvailableBytes = 0;
  const c = navigator.connection;
  out.metered = !!(c && (c.saveData || c.type === 'cellular'));
  out.ready = await readyList();
  return out;
}

// Write one chunk at an offset: a synchronous access handle where the
// browser has one (every current engine in a worker), else a writable stream.
async function writeAt(fh, offset, bytes) {
  if (fh.createSyncAccessHandle) {
    const h = await fh.createSyncAccessHandle();
    try { h.write(bytes, { at: offset }); h.flush(); } finally { h.close(); }
    return;
  }
  const w = await fh.createWritable({ keepExistingData: true });
  try { await w.write({ type: 'write', position: offset, data: bytes }); } finally { await w.close(); }
}

async function download(dir, file, key, base) {
  if (await exists(dir, file.sha256 + '.ok')) return;
  const resp = await fetch(file.url + '.chunks.json', { credentials: 'same-origin' });
  if (!resp.ok) throw new Error('unavailable: the chunk list of ' + file.label + ' answered ' + resp.status);
  const list = await resp.json();
  if (list.sha256 !== file.sha256 || list.size !== file.bytes) {
    throw fail('ChecksumMismatch', 'the chunk list does not describe ' + file.label, [['expected', file.sha256], ['actual', list.sha256 || '']]);
  }
  const fh = await dir.getFileHandle(file.sha256 + '.gguf', { create: true });
  const prog = await dir.getFileHandle(file.sha256 + '.prog', { create: true });
  let have = 0;
  try { have = parseInt(await (await prog.getFile()).text(), 10) || 0; } catch (e) { have = 0; }
  const whole = new Sha256();
  // The chunks already stored were checked when they were written; they are
  // read back only to feed the whole-file digest.
  const stored = await fh.getFile();
  if (stored.size < have * CHUNK && have > 0) have = Math.floor(stored.size / CHUNK);
  for (let i = 0; i < have; i++) {
    whole.update(new Uint8Array(await stored.slice(i * CHUNK, Math.min((i + 1) * CHUNK, list.size)).arrayBuffer()));
  }
  for (let i = have; i < list.chunks.length; i++) {
    const start = i * CHUNK, end = Math.min(start + CHUNK, list.size) - 1;
    const r = await fetch(file.url, { headers: { Range: 'bytes=' + start + '-' + end }, credentials: 'same-origin' });
    if (r.status !== 206 && !(r.status === 200 && list.chunks.length === 1)) {
      throw new Error('unavailable: ' + file.label + ' chunk ' + i + ' answered ' + r.status);
    }
    const bytes = new Uint8Array(await r.arrayBuffer());
    const got = await digestHex(bytes);
    if (got !== list.chunks[i]) {
      throw fail('ChecksumMismatch', file.label + ' chunk ' + i + ' does not match its digest', [['expected', list.chunks[i]], ['actual', got]]);
    }
    await writeAt(fh, start, bytes);
    whole.update(bytes);
    await writeAt(prog, 0, new TextEncoder().encode(String(i + 1).padEnd(12, ' ')));
    base.done += bytes.length;
    self.postMessage({ type: 'progress', key, doneBytes: base.done, totalBytes: base.total });
  }
  const sum = whole.hex();
  if (sum !== file.sha256) {
    await dir.removeEntry(file.sha256 + '.gguf').catch(() => {});
    await dir.removeEntry(file.sha256 + '.prog').catch(() => {});
    throw fail('ChecksumMismatch', file.label + ' does not match its SHA-256', [['expected', file.sha256], ['actual', sum]]);
  }
  await dir.getFileHandle(file.sha256 + '.ok', { create: true });
  await dir.removeEntry(file.sha256 + '.prog').catch(() => {});
}

let engine = null; // { variant, mod, key, call }

async function loadEngine(variant, engines) {
  if (engine && engine.variant === variant) return engine;
  const e = engines[variant === 'webgpu' ? 'webgpu' : 'cpu'];
  if (!e) throw unsupported(variant === 'webgpu' ? 'webgpu' : 'wasm-cpu', 'the build has no ' + variant + ' engine');
  const { default: create } = await import(e.mjs);
  const mod = await create({ locateFile: () => e.wasm, print: () => {}, printErr: () => {} });
  const isAsync = variant === 'webgpu';
  const call = (name, ret, types, args) => mod.ccall(name, ret, types, args, isAsync ? { async: true } : undefined);
  await call('sky_llama_init', 'number', ['number'], [0]);
  if (variant === 'webgpu') {
    const gpus = mod.ccall('sky_llama_gpu_devices', 'number', [], []);
    if (gpus === 0) {
      throw unsupported('webgpu', 'WebGPU registered no GPU device (an adapter with shader-f16 is required); the WebGPU build does not run on the CPU');
    }
  }
  mod.FS.mkdir('/m');
  engine = { variant, mod, call, key: '' };
  return engine;
}

async function ensureLoaded(msg) {
  const offer = JSON.parse(msg.offer);
  const variant = msg.backend === 'webgpu' ? 'webgpu' : 'cpu';
  const key = variant + ':' + offer.model.sha256 + ':' + (offer.adapter ? offer.adapter.sha256 : '');
  if (engine && engine.key === key) return engine;
  const dir = await storeDir();
  const need = [offer.model].concat(offer.adapter ? [offer.adapter] : []);
  for (const f of need) {
    if (!(await exists(dir, f.sha256 + '.ok'))) {
      throw fail('NotProvisioned', 'the on-device model of slot ' + offer.slot + ' is not downloaded',
        [['what', 'the on-device model of slot ' + offer.slot], ['command', 'Device.prepare "' + offer.slot + '"']]);
    }
  }
  const e = await loadEngine(variant, msg.engines);
  if (e.key) { await e.call('sky_llama_unload', null, [], []); try { e.mod.FS.unmount('/m'); } catch (x) {} }
  e.key = '';
  const blobs = [{ name: 'model.gguf', data: await (await dir.getFileHandle(offer.model.sha256 + '.gguf')).getFile() }];
  if (offer.adapter) blobs.push({ name: 'adapter.gguf', data: await (await dir.getFileHandle(offer.adapter.sha256 + '.gguf')).getFile() });
  e.mod.FS.mount(e.mod.FS.filesystems.WORKERFS, { blobs }, '/m');
  const rc = await e.call('sky_llama_load', 'number', ['string', 'number', 'number', 'number'],
    ['/m/model.gguf', variant === 'webgpu' ? 999 : 0, offer.context, 1]);
  if (rc !== 0) {
    const why = e.mod.ccall('sky_llama_last_error', 'string', [], []);
    throw fail('EngineFailed', 'the device model did not load: ' + why, [['reason', 'the device model did not load: ' + why]]);
  }
  if (offer.adapter) {
    const arc = await e.call('sky_llama_adapter', 'number', ['string', 'number'], ['/m/adapter.gguf', 1.0]);
    if (arc !== 0) {
      const why = e.mod.ccall('sky_llama_last_error', 'string', [], []);
      throw fail('EngineFailed', 'the device adapter did not load: ' + why, [['reason', 'the device adapter did not load: ' + why]]);
    }
  }
  e.key = key;
  return e;
}

async function chat(msg) {
  const e = await ensureLoaded(msg);
  if (msg.path === '/@root/tokenize') {
    const req = JSON.parse(msg.body);
    const n = await e.call('sky_llama_tokenize', 'number', ['string'], [String(req.content || '')]);
    return JSON.stringify({ tokens: new Array(Math.max(0, n)).fill(0) });
  }
  if (msg.path !== '/chat/completions') {
    throw fail('RemoteRejected', 'a device answers chat requests only', [['status', '404']]);
  }
  const out = await e.call('sky_llama_chat', 'string', ['string'], [msg.body]);
  const parsed = JSON.parse(out);
  if (parsed.error) {
    if (parsed.error.code === 'context') {
      throw fail('InvalidSetting', parsed.error.message, [['setting', 'context'], ['reason', parsed.error.message]]);
    }
    throw fail('EngineFailed', parsed.error.message, [['reason', parsed.error.message]]);
  }
  return out;
}

// engineFailure is the typed failure of an engine error object.
function engineFailure(err) {
  if (err.code === 'context') {
    return fail('InvalidSetting', err.message, [['setting', 'context'], ['reason', err.message]]);
  }
  return fail('EngineFailed', err.message, [['reason', err.message]]);
}

// Streaming (Provider.chatStream): streamBegin decodes the prompt; each
// streamNext answers {"delta":…} or, last, {"done":true,"body":"<the
// chat-completions body as a string>"}. One answer streams at a time: a new
// begin ends the one before.
async function streamBegin(msg) {
  const e = await ensureLoaded(msg);
  if (msg.path !== '/chat/completions') {
    throw fail('RemoteRejected', 'a device answers chat requests only', [['status', '404']]);
  }
  const out = await e.call('sky_llama_chat_begin', 'string', ['string'], [msg.body]);
  if (out) throw engineFailure(JSON.parse(out).error);
  return '';
}

async function streamNext() {
  if (!engine) throw fail('EngineFailed', 'no answer is streaming', [['reason', 'no answer is streaming']]);
  const ev = JSON.parse(await engine.call('sky_llama_chat_next', 'string', [], []));
  if (ev.error) throw engineFailure(ev.error);
  if (ev.done) return JSON.stringify({ done: true, body: JSON.stringify(ev.body) });
  return JSON.stringify(ev);
}

async function prepare(msg) {
  const offer = JSON.parse(msg.offer);
  const dir = await storeDir();
  const files = [offer.model].concat(offer.adapter ? [offer.adapter] : []);
  const base = { done: 0, total: files.reduce((n, f) => n + f.bytes, 0) };
  for (const f of files) {
    if (await exists(dir, f.sha256 + '.ok')) base.done += f.bytes;
  }
  for (const f of files) await download(dir, f, msg.key, base);
  await ensureLoaded(msg);
  return 'ready';
}

async function evict(msg) {
  const offer = JSON.parse(msg.offer);
  const dir = await storeDir();
  const files = [offer.model].concat(offer.adapter ? [offer.adapter] : []);
  if (engine && engine.key.indexOf(offer.model.sha256) >= 0) {
    await engine.call('sky_llama_unload', null, [], []);
    try { engine.mod.FS.unmount('/m'); } catch (x) {}
    engine.key = '';
  }
  for (const f of files) {
    for (const ext of ['.ok', '.gguf', '.prog']) await dir.removeEntry(f.sha256 + ext).catch(() => {});
  }
  return '';
}

let queue = Promise.resolve();
self.onmessage = (ev) => {
  const msg = ev.data || {};
  // One request at a time: the engine is not reentrant.
  queue = queue.then(async () => {
    try {
      let value;
      if (msg.op === 'caps') value = JSON.stringify(await caps(msg.engines || {}));
      else if (msg.op === 'prepare') value = await prepare(msg);
      else if (msg.op === 'chat') value = await chat(msg);
      else if (msg.op === 'streamBegin') value = await streamBegin(msg);
      else if (msg.op === 'streamNext') value = await streamNext();
      else if (msg.op === 'evict') value = await evict(msg);
      else throw new Error('invalid: unknown op ' + msg.op);
      self.postMessage({ id: msg.id, ok: true, value });
    } catch (e) {
      const error = (e && e.sky) ? e.sky : (e && e.message && /^[a-z]+: /.test(e.message) ? e.message : 'unavailable: ' + String(e && e.message || e));
      self.postMessage({ id: msg.id, ok: false, error });
    }
  });
};
`

