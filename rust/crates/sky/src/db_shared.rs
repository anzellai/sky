/// Which service manager the generated unit targets.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Platform {
    Systemd,
    Launchd,
}

impl Platform {
    pub fn host() -> Platform {
        if cfg!(target_os = "macos") {
            Platform::Launchd
        } else {
            Platform::Systemd
        }
    }
    pub fn name(&self) -> &'static str {
        match self {
            Platform::Systemd => "systemd",
            Platform::Launchd => "launchd",
        }
    }
}

/// Everything a unit file needs. Held as one struct so the systemd and launchd
/// generators cannot drift on which paths they name.
#[derive(Debug, Clone)]
pub struct ServiceSpec {
    pub layout: Layout,
    pub postgres: PathBuf,
    pub pg_dump: PathBuf,
    pub pg_dumpall: PathBuf,
    pub user: String,
    pub listen: Listen,
    pub backup_keep_days: u32,
    /// UTC hour and minute the backup runs at.
    pub backup_at: (u32, u32),
}

impl ServiceSpec {
    pub fn wrapper_path(&self) -> PathBuf {
        self.layout.service_dir.join("sky-postgres-run.sh")
    }
    pub fn backup_script_path(&self) -> PathBuf {
        self.layout.service_dir.join("sky-postgres-backup.sh")
    }
}

/// The systemd unit for the cluster.
///
/// `KillSignal=SIGINT` is the load-bearing line, and it is not cosmetic.
/// systemd's default stop signal is `SIGTERM`, which PostgreSQL reads as **smart
/// shutdown**: wait for every client to disconnect, however long that takes. A
/// cluster with one long-lived app connection would therefore never stop, hit
/// `TimeoutStopSec`, take a `SIGKILL`, and perform crash recovery on **every**
/// reboot. `SIGINT` is fast shutdown — disconnect clients, checkpoint, exit.
///
/// `Type=exec` (not `notify`): the bundle is built `--without-systemd`
/// (`scripts/skydb/build-postgres-bundle.sh`, an LGPL exclusion), so the
/// postmaster cannot signal readiness and `Type=notify` would hang until the
/// start timeout.
pub fn systemd_service(spec: &ServiceSpec) -> String {
    format!(
        "[Unit]\n\
         Description=Sky shared PostgreSQL cluster\n\
         Documentation=https://github.com/anzellai/sky/blob/main/docs/skydb/embedded-postgres.md\n\
         After=network.target\n\
         \n\
         [Service]\n\
         # Type=exec, not notify: sky's PostgreSQL is built --without-systemd (an\n\
         # LGPL exclusion), so it cannot send READY=1 and notify would hang.\n\
         Type=exec\n\
         User={user}\n\
         ExecStart={postgres} -D {data} -k {socket}\n\
         ExecReload=/bin/kill -HUP $MAINPID\n\
         # PostgreSQL reads SIGTERM as SMART shutdown: wait for every client to\n\
         # disconnect, indefinitely. systemd's default stop signal is SIGTERM, so\n\
         # without this line a cluster with one live app connection never stops, hits\n\
         # TimeoutStopSec, is SIGKILLed, and does crash recovery on every reboot.\n\
         # SIGINT is FAST shutdown.\n\
         KillSignal=SIGINT\n\
         KillMode=mixed\n\
         TimeoutStopSec=120\n\
         Restart=on-failure\n\
         RestartSec=5s\n\
         # The database is the last thing that should be killed under memory\n\
         # pressure: every app on this host loses its data layer with it.\n\
         OOMScoreAdjust=-900\n\
         LimitNOFILE=65536\n\
         NoNewPrivileges=true\n\
         PrivateTmp=true\n\
         ProtectSystem=full\n\
         ReadWritePaths={state}\n\
         \n\
         [Install]\n\
         WantedBy=multi-user.target\n",
        user = spec.user,
        postgres = spec.postgres.display(),
        data = spec.layout.data_dir.display(),
        socket = spec.layout.socket_dir.display(),
        state = spec.layout.state_dir.display(),
    )
}

/// The launchd job for the cluster.
///
/// It runs [`launchd_wrapper`] rather than `postgres` directly, and the reason is
/// the same signal problem systemd solves with one line: **launchd has no
/// `KillSignal`**. `launchctl unload` / `bootout` sends `SIGTERM`, which
/// PostgreSQL reads as smart shutdown — wait for every client, forever — and
/// launchd then `SIGKILL`s at `ExitTimeOut`, so every reboot ends in crash
/// recovery. The wrapper traps `SIGTERM` and turns it into the `SIGINT` the
/// postmaster needs.
pub fn launchd_plist(spec: &ServiceSpec) -> String {
    let args = vec![spec.wrapper_path().display().to_string()];
    plist_job(
        "org.sky.postgres",
        &args,
        &spec.user,
        Some(&spec.layout.log_file()),
        &[
            ("RunAtLoad", PlistValue::Bool(true)),
            (
                "KeepAlive",
                PlistValue::Dict(vec![("SuccessfulExit", PlistValue::Bool(false))]),
            ),
            ("ExitTimeOut", PlistValue::Int(120)),
            // Without this launchd applies background I/O throttling to a
            // long-running job, which on a database is indistinguishable from a
            // failing disk.
            ("ProcessType", PlistValue::Str("Interactive".into())),
            (
                "WorkingDirectory",
                PlistValue::Str(spec.layout.state_dir.display().to_string()),
            ),
        ],
    )
}

/// The launchd-only shutdown wrapper. See [`launchd_plist`] for why it exists.
///
/// The double `wait` is deliberate: POSIX `wait` returns as soon as a trapped
/// signal is handled, with the child still running its fast shutdown, so a
/// single `wait` would let the wrapper exit while PostgreSQL was still
/// checkpointing — and launchd would then reap the whole job.
pub fn launchd_wrapper(spec: &ServiceSpec) -> String {
    format!(
        "#!/bin/sh\n\
         # Generated by `sky db provision --shared --service`. Regenerated, not edited.\n\
         #\n\
         # launchd has no KillSignal: `launchctl bootout` sends SIGTERM, and PostgreSQL\n\
         # reads SIGTERM as SMART shutdown — wait for every client to disconnect, with\n\
         # no timeout. launchd then SIGKILLs at ExitTimeOut and the next start performs\n\
         # crash recovery. This traps SIGTERM and sends the postmaster the SIGINT that\n\
         # means FAST shutdown instead.\n\
         set -u\n\
         \n\
         \"{postgres}\" -D \"{data}\" -k \"{socket}\" &\n\
         pg=$!\n\
         trap 'kill -INT \"$pg\" 2>/dev/null' TERM INT\n\
         \n\
         # `wait` returns as soon as the trap runs, with the postmaster still\n\
         # checkpointing. The second `wait` is what makes \"stopped\" mean stopped.\n\
         wait \"$pg\"\n\
         rc=$?\n\
         if [ \"$rc\" -gt 128 ]; then\n\
         \x20 wait \"$pg\"\n\
         \x20 rc=$?\n\
         fi\n\
         exit \"$rc\"\n",
        postgres = spec.postgres.display(),
        data = spec.layout.data_dir.display(),
        socket = spec.layout.socket_dir.display(),
    )
}

/// The backup script both platforms schedule.
///
/// Three properties it is worth being explicit about:
///
/// * **The app list is read at run time**, from the file `--app` appends to, so
///   an app provisioned after the timer was generated is backed up without
///   regenerating anything.
/// * **A dump is renamed into place.** A `.part` left by an interrupted run is
///   never mistaken for a backup, which is the mistake that is only discovered
///   during a restore.
/// * **Roles are dumped when `pg_dumpall` is available, and the absence is
///   reported.** A `pg_dump` of one database restores into a cluster that has no
///   `app_x` role by failing on every `OWNER TO`. `pg_dumpall` is not in Sky's
///   own bundle (`scripts/skydb/build-postgres-bundle.sh` ships `postgres`,
///   `initdb`, `pg_ctl`, `pg_dump`, `pg_restore`), so this says so in the log
///   rather than quietly producing a backup that cannot be restored unattended.
pub fn backup_script(spec: &ServiceSpec) -> String {
    format!(
        "#!/bin/sh\n\
         # Generated by `sky db provision --shared --backup`. Regenerated, not edited.\n\
         #\n\
         # One server has no replica: this is the only thing standing between a bad\n\
         # afternoon and \"we lost everything\".\n\
         set -eu\n\
         umask 077\n\
         \n\
         PG_DUMP=\"{pg_dump}\"\n\
         PG_DUMPALL=\"{pg_dumpall}\"\n\
         SOCKET_DIR=\"{socket}\"\n\
         PORT=\"{port}\"\n\
         OUT=\"{out}\"\n\
         APPS=\"{apps}\"\n\
         KEEP_DAYS=\"{keep}\"\n\
         \n\
         ts=\"$(date -u +%Y%m%dT%H%M%SZ)\"\n\
         mkdir -p \"$OUT\"\n\
         \n\
         # Roles are cluster-wide, so a per-database dump restores with no owner to\n\
         # give its objects to. pg_dumpall is not in Sky's own PostgreSQL bundle; when\n\
         # it is missing the backup is still taken, and the gap is stated.\n\
         if [ -x \"$PG_DUMPALL\" ]; then\n\
         \x20 tmp=\"$OUT/.globals-$ts.sql.part\"\n\
         \x20 \"$PG_DUMPALL\" --host \"$SOCKET_DIR\" --port \"$PORT\" --globals-only --file \"$tmp\"\n\
         \x20 mv \"$tmp\" \"$OUT/globals-$ts.sql\"\n\
         else\n\
         \x20 echo \"sky-postgres-backup: $PG_DUMPALL is not present - role definitions are NOT in this backup\" >&2\n\
         fi\n\
         \n\
         if [ ! -f \"$APPS\" ]; then\n\
         \x20 echo \"sky-postgres-backup: no app list at $APPS; nothing to dump\" >&2\n\
         \x20 exit 0\n\
         fi\n\
         \n\
         while IFS= read -r db; do\n\
         \x20 [ -n \"$db\" ] || continue\n\
         \x20 case \"$db\" in '#'*) continue ;; esac\n\
         \x20 tmp=\"$OUT/.$db-$ts.dump.part\"\n\
         \x20 # --format=custom: pg_restore can select objects out of it, and it is\n\
         \x20 # compressed. A plain-SQL dump is only restorable by psql, which sky's\n\
         \x20 # bundle deliberately does not ship.\n\
         \x20 #\n\
         \x20 # RESTORE WITH --create:\n\
         \x20 #   pg_restore --create --dbname postgres <dump>\n\
         \x20 # The archive carries the database's own ACL - the REVOKE that keeps\n\
         \x20 # every other app role out - as a DATABASE-section entry, and\n\
         \x20 # pg_restore applies that section ONLY with --create. Restored into a\n\
         \x20 # database made by hand instead, the result carries PUBLIC's default\n\
         \x20 # CONNECT and every app role on this cluster can read it.\n\
         \x20 \"$PG_DUMP\" --host \"$SOCKET_DIR\" --port \"$PORT\" --format=custom --file \"$tmp\" -- \"$db\"\n\
         \x20 mv \"$tmp\" \"$OUT/$db-$ts.dump\"\n\
         done < \"$APPS\"\n\
         \n\
         # Retention. Without this the disk fills and the backup that matters is the\n\
         # one that failed for want of space.\n\
         find \"$OUT\" -type f -name '*.dump' -mtime \"+$KEEP_DAYS\" -delete\n\
         find \"$OUT\" -type f -name 'globals-*.sql' -mtime \"+$KEEP_DAYS\" -delete\n\
         find \"$OUT\" -type f -name '.*.part' -mtime +1 -delete\n",
        pg_dump = spec.pg_dump.display(),
        pg_dumpall = spec.pg_dumpall.display(),
        socket = spec.layout.socket_dir.display(),
        port = spec.listen.port,
        out = spec.layout.backup_dir.display(),
        apps = spec.layout.apps_file.display(),
        keep = spec.backup_keep_days,
    )
}

