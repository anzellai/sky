/// The default port. A shared cluster is socket-only unless `--listen` is given,
/// but the socket file is still named `.s.PGSQL.<port>`, so the number matters
/// even with no TCP listener.
pub const DEFAULT_PORT: u16 = 5432;

const CONF_BEGIN: &str = "# --- sky shared cluster: managed block (regenerated by sky) ---";
const CONF_END: &str = "# --- end sky shared cluster block ---";

// ---- layout --------------------------------------------------------------

/// Every path the shared cluster owns, derived from one state directory.
///
/// The socket directory is a **sibling** of the data directory, never a child.
/// PostgreSQL requires the data directory to be mode 0700, so a socket inside it
/// is unreachable by any other user — which is precisely the case a shared
/// cluster exists for, several apps under several accounts on one host.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Layout {
    pub state_dir: PathBuf,
    pub data_dir: PathBuf,
    pub socket_dir: PathBuf,
    pub service_dir: PathBuf,
    pub backup_dir: PathBuf,
    pub log_dir: PathBuf,
    pub apps_file: PathBuf,
}

impl Layout {
    pub fn new(state_dir: &Path) -> Layout {
        Layout {
            state_dir: state_dir.to_path_buf(),
            data_dir: state_dir.join("pg"),
            socket_dir: state_dir.join("run"),
            service_dir: state_dir.join("service"),
            backup_dir: state_dir.join("backups"),
            log_dir: state_dir.join("log"),
            apps_file: state_dir.join("apps"),
        }
    }

    pub fn log_file(&self) -> PathBuf {
        self.log_dir.join("postgres.log")
    }
}

/// `/var/lib/sky` on Linux, `/usr/local/var/sky` on macOS — the conventional
/// place for a service's mutable state on each platform. `$SKY_SHARED_STATE_DIR`
/// overrides it, and `--state-dir` overrides that.
pub fn default_state_dir() -> PathBuf {
    if let Some(v) = std::env::var_os("SKY_SHARED_STATE_DIR").filter(|v| !v.is_empty()) {
        return PathBuf::from(v);
    }
    if cfg!(target_os = "macos") {
        PathBuf::from("/usr/local/var/sky")
    } else {
        PathBuf::from("/var/lib/sky")
    }
}

/// Why a state directory is unusable, or `None` when it is fine.
///
/// Three refusals, each for a failure that would surface much later than here:
///
/// * **Relative** — the path is written into a service unit that runs with an
///   arbitrary working directory, so a relative one names a different place for
///   the service manager than it did for the operator.
/// * **Ephemeral** — `/tmp`, `/var/tmp`, `/dev/shm`, macOS's `/var/folders` and
///   `$TMPDIR` are emptied by the system. A cluster that silently reinitialises
///   is indistinguishable from an app that lost every row. This is the same
///   refusal `runtime-go/rt/pg_embed.go` makes for `./app --embed`.
/// * **Inside a Sky project** — a shared cluster outlives any one project and is
///   read by other users' apps; `.skydata/` is the per-project mode, and a state
///   directory under a checkout would be deleted by a `git clean` and lost by a
///   redeploy.
///
/// Plus the shell-safety predicate: `pg_ctl start` builds one command string and
/// hands it to `/bin/sh -c`, so a `$(…)` in any interpolated path is executed.
pub fn state_dir_error(dir: &Path) -> Option<String> {
    if !dir.is_absolute() {
        return Some(format!(
            "sky db provision --shared: --state-dir must be an absolute path (got {}).\n\
             It is written into a service unit, which runs from a working directory\n\
             the operator does not choose.",
            dir.display()
        ));
    }
    let s = dir.to_string_lossy().to_string();
    let mut ephemeral: Vec<String> = ["/tmp", "/var/tmp", "/dev/shm", "/private/tmp", "/private/var/tmp", "/var/folders"]
        .iter()
        .map(|p| (*p).to_string())
        .collect();
    if let Some(t) = std::env::var_os("TMPDIR").filter(|t| !t.is_empty()) {
        ephemeral.push(t.to_string_lossy().trim_end_matches('/').to_string());
    }
    if let Some(hit) = ephemeral
        .iter()
        .find(|p| s == **p || s.starts_with(&format!("{p}/")))
    {
        return Some(format!(
            "sky db provision --shared: {} is under {hit}, which the system empties.\n\
             This directory holds the only copy of every app's data on this host; a\n\
             cluster that silently reinitialises looks exactly like an app that lost\n\
             every row. Pick a durable path, e.g. --state-dir {}.",
            dir.display(),
            default_state_dir().display()
        ));
    }
    for anc in dir.ancestors() {
        if anc.join("sky.toml").is_file() {
            return Some(format!(
                "sky db provision --shared: {} is inside the Sky project at {}.\n\
                 A shared cluster outlives any one project and is read by other apps —\n\
                 a `git clean` or a redeploy would take it with them. The per-project\n\
                 cluster is `sky db start`, which keeps its data in .skydata/.\n\
                 Pass --state-dir with a path outside the project.",
                dir.display(),
                anc.display()
            ));
        }
    }
    if !db_cluster::socket_dir_is_shell_safe(dir) {
        return Some(format!(
            "sky db provision --shared: {} contains characters a shell would interpret.\n\
             pg_ctl runs the postmaster through `/bin/sh -c` (start_postmaster in\n\
             pg_ctl.c), so a `$(…)`, a backtick or a quote in this path would be\n\
             EXECUTED. Quoting cannot make that safe; pick a plain path.",
            dir.display()
        ));
    }
    None
}

// ---- host facts and tuning ----------------------------------------------

/// What the machine has, as the tuning is derived from it.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct HostFacts {
    pub mem_bytes: u64,
    pub cpus: u32,
    /// Whether the platform has `posix_fadvise`, which decides whether
    /// `effective_io_concurrency` may be set at all.
    ///
    /// This is not a portability nicety. PostgreSQL **refuses to start** —
    /// `FATAL: configuration file … contains errors`, preceded by
    /// `effective_io_concurrency must be set to 0 on platforms that lack
    /// posix_fadvise()` — when the setting is non-zero on such a platform, and
    /// macOS is one. A generated tuning block carrying `200` unconditionally
    /// therefore produces a cluster that cannot be started, on the developer
    /// machine most likely to try it first.
    pub posix_fadvise: bool,
}

/// Real RAM and CPU count.
///
/// `SKY_PG_TUNE_MEM_MB` overrides the detected RAM. That is not a test hook: in
/// a container, `/proc/meminfo` reports the **host's** memory, not the cgroup
/// limit, so an auto-tuned `shared_buffers` is sized for RAM the cluster may not
/// touch and the OOM killer arrives instead of a slow query. The override is the
/// documented way to state the budget this cluster actually has.
pub fn detect_host() -> HostFacts {
    let cpus = std::thread::available_parallelism().map(|n| n.get() as u32).unwrap_or(2);
    let posix_fadvise = cfg!(target_os = "linux");
    if let Some(mb) = std::env::var("SKY_PG_TUNE_MEM_MB").ok().and_then(|v| v.trim().parse::<u64>().ok()) {
        if mb > 0 {
            return HostFacts { mem_bytes: mb * 1024 * 1024, cpus, posix_fadvise };
        }
    }
    HostFacts {
        mem_bytes: detect_mem_bytes().unwrap_or(2 * 1024 * 1024 * 1024),
        cpus,
        posix_fadvise,
    }
}

fn detect_mem_bytes() -> Option<u64> {
    if cfg!(target_os = "macos") {
        let out = Command::new("sysctl").args(["-n", "hw.memsize"]).output().ok()?;
        return String::from_utf8_lossy(&out.stdout).trim().parse().ok();
    }
    let text = std::fs::read_to_string("/proc/meminfo").ok()?;
    let line = text.lines().find(|l| l.starts_with("MemTotal:"))?;
    let kb: u64 = line.split_whitespace().nth(1)?.parse().ok()?;
    Some(kb * 1024)
}

/// How the cluster is reachable. Socket-only by default: "nothing is exposed to
/// the network by accident" is the rule the development supervisor already
/// follows, and several apps on ONE host reach a socket perfectly well.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Listen {
    pub addr: Option<String>,
    pub port: u16,
}

impl Default for Listen {
    fn default() -> Self {
        Listen { addr: None, port: DEFAULT_PORT }
    }
}

/// The production tuning block, derived from the host.
///
/// Every setting here is a **resource or cost** knob. Nothing that changes what
/// a query means is set — not `fsync`, not `synchronous_commit`, not
/// `wal_level` — for the reason the development profile gives: a cluster that
/// behaves differently from the one an app was written against reintroduces, in
/// a subtler form, the divergence this whole feature exists to remove.
///
/// `logging_collector` is deliberately **off**. Under systemd stderr is the
/// journal and under launchd it is `StandardErrorPath`; turning the collector on
/// would put the log somewhere neither service manager knows about, and
/// `journalctl -u sky-postgres` would show nothing.
pub fn tuning_block(h: &HostFacts, max_connections: u32, listen: &Listen, socket_dir: &Path) -> String {
    let mem_mb = h.mem_bytes / (1024 * 1024);
    let shared_buffers = (mem_mb / 4).clamp(128, 8192);
    let effective_cache = (mem_mb * 3 / 4).max(256);
    let maintenance = (mem_mb / 16).clamp(64, 2048);
    let work_mem_kb = ((mem_mb * 1024) / (max_connections as u64 * 8)).clamp(4096, 65536);
    let max_wal = (mem_mb / 4).clamp(512, 8192);
    let min_wal = (max_wal / 4).max(128);
    let workers = h.cpus.max(8);
    let parallel = h.cpus.max(2);
    let per_gather = (h.cpus / 2).clamp(1, 4);
    let autovac = (h.cpus / 2).clamp(3, 8);
    let listen_addresses = listen.addr.clone().unwrap_or_default();
    // Omitted, not set to 0, where the platform lacks posix_fadvise: PostgreSQL
    // treats a non-zero value there as a configuration ERROR and refuses to
    // start. See `HostFacts::posix_fadvise`.
    let io_concurrency = if h.posix_fadvise {
        "effective_io_concurrency = 200\n"
    } else {
        "# effective_io_concurrency is omitted: this platform lacks posix_fadvise(),\n\
         # and PostgreSQL refuses to START with a non-zero value there.\n"
    };
    format!(
        "{CONF_BEGIN}\n\
         # Tuned for {mem_mb} MB of RAM and {cpus} CPUs. Resource and planner-cost\n\
         # knobs only: nothing here changes what a query MEANS, so an app behaves the\n\
         # same against this cluster as against the development one.\n\
         #\n\
         # Regenerated in place by `sky db provision --shared`. Edits inside this\n\
         # block are overwritten; put your own settings OUTSIDE it (PostgreSQL takes\n\
         # the last occurrence of a setting, so anything after this block wins).\n\
         listen_addresses = '{listen_addresses}'\n\
         port = {port}\n\
         unix_socket_directories = '{socket}'\n\
         # The apps run as their own users and must reach the socket, so it is not\n\
         # the 0700 directory a development cluster hides behind: on a shared\n\
         # cluster the access control is authentication (see pg_hba.conf), and the\n\
         # socket's own mode is PostgreSQL's default.\n\
         unix_socket_permissions = 0777\n\
         max_connections = {max_connections}\n\
         shared_buffers = {shared_buffers}MB\n\
         effective_cache_size = {effective_cache}MB\n\
         maintenance_work_mem = {maintenance}MB\n\
         work_mem = {work_mem_kb}kB\n\
         max_wal_size = {max_wal}MB\n\
         min_wal_size = {min_wal}MB\n\
         checkpoint_completion_target = 0.9\n\
         wal_compression = on\n\
         random_page_cost = 1.1\n\
         {io_concurrency}\
         max_worker_processes = {workers}\n\
         max_parallel_workers = {parallel}\n\
         max_parallel_workers_per_gather = {per_gather}\n\
         max_parallel_maintenance_workers = {per_gather}\n\
         autovacuum_max_workers = {autovac}\n\
         autovacuum_naptime = 30s\n\
         password_encryption = 'scram-sha-256'\n\
         log_destination = 'stderr'\n\
         logging_collector = off\n\
         log_line_prefix = '%m [%p] %q%u@%d '\n\
         log_checkpoints = on\n\
         log_autovacuum_min_duration = 10s\n\
         {CONF_END}\n",
        cpus = h.cpus,
        port = listen.port,
        socket = socket_dir.display(),
    )
}

/// Replace the managed block, or append it when the file has none.
///
/// Replacement rather than `db_cluster::ensure_sky_conf`'s "append unless a
/// marker is present": a shared cluster is **re-tuned** when the host changes or
/// `--max-connections` moves, and an append-only block would leave the old
/// values in the file above the new ones. (PostgreSQL takes the last occurrence,
/// so that would happen to work — and would leave a file no operator could read.)
pub fn apply_managed_block(conf: &str, block: &str) -> String {
    let Some(start) = conf.find(CONF_BEGIN) else {
        let mut out = conf.to_string();
        if !out.ends_with('\n') && !out.is_empty() {
            out.push('\n');
        }
        out.push('\n');
        out.push_str(block);
        return out;
    };
    let end = match conf[start..].find(CONF_END) {
        Some(e) => start + e + CONF_END.len(),
        // A truncated block (an interrupted write) is replaced to end-of-file
        // rather than left to merge with the new one.
        None => conf.len(),
    };
    let mut out = String::with_capacity(conf.len());
    out.push_str(&conf[..start]);
    out.push_str(block.trim_end_matches('\n'));
    out.push_str(conf[end..].trim_start_matches('\n'));
    if !out.ends_with('\n') {
        out.push('\n');
    }
    out
}

// ---- pg_hba --------------------------------------------------------------

/// The client authentication file, generated **whole**.
///
/// It is not appended to, and that is the trap this function exists to avoid:
/// `pg_hba.conf` is first-match-wins, and `initdb` writes `local all all trust`
/// near the top. A `scram-sha-256` line appended after it is never reached — the
/// file would *look* right in review, every app would authenticate with `trust`,
/// and any local process could connect as any role simply by claiming to be it.
/// Every `REVOKE` behind that would be decoration.
///
/// The superuser keeps `peer` (the kernel's own answer to "which uid connected"),
/// so sky administers the cluster without a password to store anywhere; every
/// other role must present one.
pub fn pg_hba(superuser: &str, listen: &Listen) -> String {
    let mut s = String::from(
        "# Generated by `sky db provision --shared`. sky owns this file and\n\
         # regenerates it; put local additions in a file you include from here.\n\
         #\n\
         # FIRST MATCH WINS. The superuser line must come first, and the\n\
         # scram-sha-256 line for `all` must come before any broader method — an\n\
         # appended rule below a `trust` line is dead, and a dead rule here means\n\
         # any local process may connect as any app's role.\n\
         #\n\
         # TYPE  DATABASE        USER            ADDRESS                 METHOD\n",
    );
    s.push_str(&format!("local   all             {superuser:<15} peer\n"));
    s.push_str(&format!("local   replication     {superuser:<15} peer\n"));
    s.push_str("local   all             all             scram-sha-256\n");
    if listen.addr.is_some() {
        s.push_str(
            "# TCP was asked for with --listen. Loopback and link-local only, and\n\
             # scram-sha-256 there too — a shared cluster reachable from the network\n\
             # with a weaker method is the whole boundary gone.\n",
        );
        s.push_str("host    all             all             127.0.0.1/32            scram-sha-256\n");
        s.push_str("host    all             all             ::1/128                 scram-sha-256\n");
    }
    s
}

// ---- identifiers, names, credentials -------------------------------------

/// Names sky will not provision, because taking them would collide with the
/// cluster's own furniture.
const RESERVED: &[&str] = &["postgres", "template0", "template1", "public", "sky", "root", "all"];

/// An app name has to be usable, unquoted, as a database name, a role name and a
/// filename in the backup directory — so it is restricted rather than escaped.
///
/// Escaping would be enough for the SQL (and [`quote_ident`] applies it anyway,
/// belt and braces), but the same string is written into a shell script's `for`
/// loop and into a dump filename, and there is no single quoting that is correct
/// in all three.
pub fn validate_app_name(name: &str) -> Result<(), String> {
    let ok = !name.is_empty()
        && name.len() <= 48
        && name.starts_with(|c: char| c.is_ascii_lowercase())
        && name.chars().all(|c| c.is_ascii_lowercase() || c.is_ascii_digit() || c == '_');
    if !ok {
        return Err(format!(
            "sky db provision --shared --app: {name:?} is not a usable app name.\n\
             Use 1-48 characters of [a-z0-9_], starting with a letter: the name becomes\n\
             a database, a role and a backup filename, and there is no quoting that is\n\
             correct in all three."
        ));
    }
    if RESERVED.contains(&name) || name.starts_with("pg_") {
        return Err(format!(
            "sky db provision --shared --app: {name:?} is reserved.\n\
             `pg_*` is PostgreSQL's own namespace, and the others name the cluster's\n\
             built-in databases and roles."
        ));
    }
    // The one reserved name that cannot be a constant: the account that ran
    // `--shared` is the cluster's BOOTSTRAP SUPERUSER (`initdb --username=…`),
    // and its name is whatever that account is called. Provisioning an app of
    // that name finds the role present and — before this refusal — reset its
    // password and printed it as an app DSN: an app handed superuser, every
    // other app's data with it, and the operator's own account given a password
    // it did not choose. `--app deploy` on a host provisioned by `deploy` is the
    // realistic shape.
    if os_user().map(|u| u == name).unwrap_or(false) {
        return Err(format!(
            "sky db provision --shared --app: {name:?} is this account, and this account is\n\
             the cluster's bootstrap superuser — the role `initdb --username` created.\n\
             An app of that name would be handed the superuser's credentials, which read\n\
             every other app's database. Name the app after the app:\n\
             \x20 sky db provision --shared --app {name}_app"
        ));
    }
    Ok(())
}

/// SQL identifier quoting. Applied even though [`validate_app_name`] has already
/// made it unnecessary — the two are independent, and a later caller that skips
/// the validator must not thereby gain an injection.
pub fn quote_ident(s: &str) -> String {
    format!("\"{}\"", s.replace('"', "\"\""))
}

/// SQL string literal quoting, for the one literal that is not an identifier:
/// the generated password.
pub fn quote_literal(s: &str) -> String {
    format!("'{}'", s.replace('\'', "''"))
}

/// A generated password: 32 characters of `[A-Za-z0-9]`, ~190 bits.
///
/// The alphabet is deliberately alphanumeric-only. The password is handed to the
/// operator inside a `postgresql://` URI, and every other printable character
/// would need percent-encoding there — a DSN that has to be escaped before use
/// is a DSN that will be pasted wrong. Drawn by rejection sampling so the
/// distribution is flat; `% 62` over bytes would bias the first eight letters.
pub fn generate_password() -> String {
    const ALPHABET: &[u8] = b"ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789";
    let mut out = String::with_capacity(32);
    while out.len() < 32 {
        for b in pg_wire::random_bytes(48) {
            if (b as usize) < 248 {
                out.push(ALPHABET[(b % 62) as usize] as char);
                if out.len() == 32 {
                    break;
                }
            }
        }
    }
    out
}

/// The DSN an app is handed.
///
/// `postgresql://` (not the libpq keyword form) because that is the shape both
/// `rt.detectDriver` and the compiler's `driver_for_dsn` classify as Postgres
/// from the prefix alone. Over a socket the host goes in the query string, which
/// is libpq's documented way to name a socket **directory**.
///
/// An IPv6 address is bracketed, per RFC 3986 — and this is not cosmetic.
/// `postgresql://alpha:pw@::1:5432/alpha` is not a DSN libpq can parse: it reads
/// everything after the first colon as the port and refuses with `invalid
/// integer value ":1:5432" for connection option "port"`. The error names the
/// PORT, so an operator handed that DSN debugs the listener rather than the
/// string — and `pg_hba` emits a `::1/128` rule whenever `--listen` is given, so
/// this is an address sky explicitly supports.
pub fn app_dsn(app: &str, password: &str, socket_dir: &Path, listen: &Listen) -> String {
    match &listen.addr {
        Some(addr) => format!("postgresql://{app}:{password}@{}:{}/{app}", uri_host(addr), listen.port),
        None => format!(
            "postgresql://{app}:{password}@/{app}?host={}{}",
            socket_dir.display(),
            if listen.port == DEFAULT_PORT { String::new() } else { format!("&port={}", listen.port) }
        ),
    }
}

/// The host component of a URI: an IPv6 literal has to be bracketed, anything
/// else is written as-is. Idempotent, so an operator who passed
/// `--listen '[::1]'` does not get double brackets.
fn uri_host(addr: &str) -> String {
    if addr.contains(':') && !addr.starts_with('[') {
        format!("[{addr}]")
    } else {
        addr.to_string()
    }
}

// ---- the SQL that is the security boundary -------------------------------

/// Cluster-wide hardening, run once at provision time in the `postgres` and
/// `template1` databases.
///
/// `PUBLIC` is the trap this closes. Every role is a member of it implicitly,
/// and by default `PUBLIC` may **connect to every database in the cluster**. So
/// creating a database per app and a role per app, on its own, buys nothing: app
/// A connects to app B's database as a matter of course.
///
/// `template1` matters for a second reason. Before PostgreSQL 15, `PUBLIC` also
/// held `CREATE` on every `public` schema — including `template1`'s, which is
/// **copied into every database created afterwards**. An app that created a
/// table there would have it appear inside every app provisioned later. The
/// bundle pins 18.6, where the schema default is already closed, but a shared
/// cluster may be an operator's existing server of any version, so this is
/// applied rather than assumed.
///
/// The scope of the guarantee is exactly the databases sky provisions plus the
/// two it hardens here. A database an operator creates by hand in this cluster
/// keeps `PUBLIC`'s default `CONNECT`, and every app role may therefore reach
/// it — `REVOKE ALL ON DATABASE … FROM PUBLIC` is per-database and there is no
/// cluster-wide default to set. Sky says "refused by every database sky
/// provisioned" rather than "and nothing else" for that reason.
pub fn cluster_hardening_sql(db: &str) -> Vec<String> {
    let mut v = vec![
        "REVOKE ALL ON SCHEMA public FROM PUBLIC".to_string(),
        "REVOKE ALL ON DATABASE template1 FROM PUBLIC".to_string(),
    ];
    if db == "postgres" {
        v.push("REVOKE ALL ON DATABASE postgres FROM PUBLIC".to_string());
    }
    v
}

/// The statements that create one app's slice, run in the `postgres` database.
///
/// The `REVOKE` is the security boundary; the `CREATE`s only make the objects.
/// Without `REVOKE ALL ON DATABASE … FROM PUBLIC` every other app's role may
/// connect here, read the catalog, and — on a server where `PUBLIC` still holds
/// `CREATE` on `public` — leave objects behind.
///
/// The role is created with every "may do more than its own database" attribute
/// explicitly off. They are the defaults; stating them means a later reader can
/// see the intent, and a `CREATEROLE` that appeared by accident would stand out.
pub fn app_cluster_sql(app: &str, password: &str) -> Vec<String> {
    let id = quote_ident(app);
    vec![
        format!(
            "CREATE ROLE {id} LOGIN PASSWORD {} NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION NOBYPASSRLS",
            quote_literal(password)
        ),
        // Sky's mark on the roles it owns. A later `--app` run of the same name
        // has to tell its own role from an operator's `analytics`, a previous
        // tenant's, or the bootstrap superuser — and the answer must live in the
        // cluster, next to the role, so that it survives a state directory that
        // was restored, copied or lost. See [`provision_app_inner`], which
        // refuses to touch a role that does not carry it.
        format!("COMMENT ON ROLE {id} IS {}", quote_literal(ROLE_MARKER)),
        format!("CREATE DATABASE {id} OWNER {id}"),
        // The database's half of the same mark. Without it the ownership
        // question could only be asked about the ROLE, and `--app` over an
        // operator's existing DATABASE — the one case where the role is absent
        // and the database is not — walked straight past the refusal and
        // re-owned it. See [`refuse_a_database_sky_does_not_own`].
        format!("COMMENT ON DATABASE {id} IS {}", quote_literal(DB_MARKER)),
        format!("REVOKE ALL ON DATABASE {id} FROM PUBLIC"),
        format!("GRANT CONNECT, TEMPORARY ON DATABASE {id} TO {id}"),
    ]
}

/// The comment sky puts on every role it creates. Ownership, recorded in the
/// cluster rather than only in `apps_file`.
pub const ROLE_MARKER: &str = "sky shared-cluster app role";

/// The comment sky puts on every database it creates, and the answer to "is
/// this database mine to re-own?".
///
/// A role marker on its own is not enough, because a role and a database of the
/// same name are two independent objects and an operator's host routinely has
/// one without the other. `shobj_description(oid, 'pg_database')` reads it back;
/// like [`ROLE_MARKER`] it lives in the cluster rather than in `apps_file` so
/// that it survives a state directory that was restored, copied or lost.
pub const DB_MARKER: &str = "sky shared-cluster app database";

/// The statements run **inside** the app's own database, once it exists.
///
/// Ownership of `public` is transferred rather than relying on the version's
/// default: before PostgreSQL 15 the schema is owned by the bootstrap superuser
/// and `PUBLIC` may create in it; from 15 it is owned by `pg_database_owner`.
/// Setting the owner explicitly makes the app's rights the same on both.
pub fn app_database_sql(app: &str) -> Vec<String> {
    let id = quote_ident(app);
    vec![
        "REVOKE ALL ON SCHEMA public FROM PUBLIC".to_string(),
        format!("ALTER SCHEMA public OWNER TO {id}"),
        format!("GRANT ALL ON SCHEMA public TO {id}"),
    ]
}

/// Re-applied on every `--app` run so a cluster provisioned by an older sky, or
/// hand-edited, converges. Idempotent by construction: every statement states an
/// end state.
pub fn app_regrant_sql(app: &str) -> Vec<String> {
    let id = quote_ident(app);
    vec![
        format!("REVOKE ALL ON DATABASE {id} FROM PUBLIC"),
        format!("GRANT CONNECT, TEMPORARY ON DATABASE {id} TO {id}"),
    ]
}

pub fn rotate_sql(app: &str, password: &str) -> String {
    format!("ALTER ROLE {} PASSWORD {}", quote_ident(app), quote_literal(password))
}

