//! `sky db provision --shared` — the shared-cluster service mode (phase 6).
//!
//! The design decision this implements is stated in
//! `docs/skydb/embedded-postgres.md`:
//!
//! > **Production, several apps on one host — one shared cluster.** Per-app
//! > clusters would mean a postmaster, a WAL, an autovacuum launcher, a backup
//! > job and a tuning pass *each*. Instead: one tuned cluster, **database-per-app
//! > and role-per-app**. The role boundary is load-bearing, not hygiene — an
//! > app's credentials must not be able to read another app's database, and that
//! > is enforced by PostgreSQL roles rather than by convention.
//!
//! Four things are produced, and the first is the reason for the other three.
//!
//! 1. **A database and a role per app**, the role granted on its own database
//!    and nothing else, with `PUBLIC`'s defaults revoked. See
//!    [`app_cluster_sql`] for what "and nothing else" costs in statements, and
//!    why `REVOKE … FROM PUBLIC` is the load-bearing half.
//! 2. **A cluster at a stable, non-project-local state directory**, tuned from
//!    the host's real RAM and CPU rather than from the development profile in
//!    `db_cluster::sky_conf_block` — this one serves production traffic.
//! 3. **An OS service unit**, so the cluster's lifecycle belongs to systemd or
//!    launchd rather than to a `sky run` that will exit.
//! 4. **A backup timer**, because a single server has no replica and "I lost
//!    everything" is the failure mode a shared host actually meets.
//!
//! # The verb shape, and why it is `sky db provision --shared`
//!
//! `provision` already means "make the PostgreSQL this machine needs exist":
//! `--embed` provisions the *binaries* (phase 3). `--shared` provisions the
//! *cluster* those binaries run, and `--shared --app <name>` provisions one
//! app's slice of it. A separate top-level verb (`sky db serve`, `sky db host`)
//! would have put two halves of one operator story under two nouns, and
//! `sky db start` / `stop` / `ps` are already spoken for by the per-project
//! development supervisor — reusing them for a machine-wide service would make
//! `sky db stop` mean "stop my project's cluster" in one directory and "stop
//! every app on this host" in another.
//!
//! The `--app` sub-shape is incremental on purpose: apps arrive one at a time,
//! long after the cluster was provisioned, and adding the fifth app must not
//! re-tune or restart the four that are serving traffic.

use std::path::{Path, PathBuf};
use std::process::{Command, ExitCode, Stdio};

