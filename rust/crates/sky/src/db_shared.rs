enum PlistValue {
    Bool(bool),
    Int(i64),
    Str(String),
    Dict(Vec<(&'static str, PlistValue)>),
}

fn plist_value(v: &PlistValue, indent: usize) -> String {
    let pad = " ".repeat(indent);
    match v {
        PlistValue::Bool(b) => format!("{pad}<{}/>\n", if *b { "true" } else { "false" }),
        PlistValue::Int(i) => format!("{pad}<integer>{i}</integer>\n"),
        PlistValue::Str(s) => format!("{pad}<string>{}</string>\n", xml_escape(s)),
        PlistValue::Dict(kvs) => {
            let mut out = format!("{pad}<dict>\n");
            for (k, v) in kvs {
                out.push_str(&format!("{pad}  <key>{k}</key>\n"));
                out.push_str(&plist_value(v, indent + 2));
            }
            out.push_str(&format!("{pad}</dict>\n"));
            out
        }
    }
}

fn plist_job(
    label: &str,
    args: &[String],
    user: &str,
    log: Option<&Path>,
    extra: &[(&'static str, PlistValue)],
) -> String {
    let mut out = String::from(
        "<?xml version=\"1.0\" encoding=\"UTF-8\"?>\n\
         <!DOCTYPE plist PUBLIC \"-//Apple//DTD PLIST 1.0//EN\" \
         \"http://www.apple.com/DTDs/PropertyList-1.0.dtd\">\n\
         <plist version=\"1.0\">\n\
         <dict>\n",
    );
    out.push_str(&format!("  <key>Label</key>\n  <string>{}</string>\n", xml_escape(label)));
    out.push_str("  <key>ProgramArguments</key>\n  <array>\n");
    for a in args {
        out.push_str(&format!("    <string>{}</string>\n", xml_escape(a)));
    }
    out.push_str("  </array>\n");
    out.push_str(&format!("  <key>UserName</key>\n  <string>{}</string>\n", xml_escape(user)));
    if let Some(l) = log {
        out.push_str(&format!(
            "  <key>StandardOutPath</key>\n  <string>{}</string>\n\
             \x20 <key>StandardErrorPath</key>\n  <string>{}</string>\n",
            xml_escape(&l.display().to_string()),
            xml_escape(&l.display().to_string())
        ));
    }
    for (k, v) in extra {
        out.push_str(&format!("  <key>{k}</key>\n"));
        out.push_str(&plist_value(v, 2));
    }
    out.push_str("</dict>\n</plist>\n");
    out
}

fn xml_escape(s: &str) -> String {
    s.replace('&', "&amp;").replace('<', "&lt;").replace('>', "&gt;")
}

/// What the operator must run to install what was generated. Sky writes the unit
/// files into the state directory and stops there: installing them means writing
/// under `/etc` or `/Library`, which needs privileges sky does not ask for, and
/// a tool that silently acquires them is worse than one that prints two lines.
pub fn install_instructions(platform: Platform, spec: &ServiceSpec, backup: bool) -> String {
    let dir = spec.layout.service_dir.display();
    match platform {
        Platform::Systemd => {
            let mut s = format!(
                "Install the service (as root):\n\
                 \x20 sudo cp {dir}/sky-postgres.service /etc/systemd/system/\n"
            );
            if backup {
                s.push_str(&format!(
                    "\x20 sudo cp {dir}/sky-postgres-backup.service {dir}/sky-postgres-backup.timer \\\n\
                     \x20      /etc/systemd/system/\n"
                ));
            }
            s.push_str("\x20 sudo systemctl daemon-reload\n\x20 sudo systemctl enable --now sky-postgres.service\n");
            if backup {
                s.push_str("\x20 sudo systemctl enable --now sky-postgres-backup.timer\n");
            }
            s
        }
        Platform::Launchd => {
            let mut s = format!(
                "Install the service (as root):\n\
                 \x20 sudo cp {dir}/org.sky.postgres.plist /Library/LaunchDaemons/\n\
                 \x20 sudo launchctl bootstrap system /Library/LaunchDaemons/org.sky.postgres.plist\n"
            );
            if backup {
                s.push_str(&format!(
                    "\x20 sudo cp {dir}/org.sky.postgres-backup.plist /Library/LaunchDaemons/\n\
                     \x20 sudo launchctl bootstrap system /Library/LaunchDaemons/org.sky.postgres-backup.plist\n"
                ));
            }
            s
        }
    }
}

