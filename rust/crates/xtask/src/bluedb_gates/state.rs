//! `docs/bluedb/gate-state.tsv` — the committed, cross-run ledger.
//!
//! §9 specifies two facts that must outlive a single invocation but that
//! `STATUS.md` cannot itself carry, because `STATUS.md` is regenerated from the
//! registry on every run:
//!
//! * **the last FULL-tier run** (§9.3 property 4 — two staleness clocks). A
//!   fast run must not be able to "refresh" a status whose hard gates are weeks
//!   old, so the full-tier commit is recorded separately and only `--tier=full`
//!   updates it.
//! * **the mutation proof ledger** (§9.4 / MAJOR-17). `--verify-mutations` is
//!   too expensive for the default command, so its verdicts are recorded here
//!   and the default command renders `PROVEN @ <sha>` from the ledger —
//!   downgrading it to `UNVERIFIED-SINCE <sha>` when the mutation's declared
//!   `targets` have moved.
//!
//! Format is line-oriented TSV, not JSON, so the file is a reviewable diff and
//! the crate needs no serialisation dependency.
//!
//! ```text
//! full-tier<TAB><commit><TAB><rfc3339><TAB><host>
//! proof<TAB><mutation-id><TAB><outcome><TAB><commit>
//! ```

use std::collections::BTreeMap;
use std::path::Path;

pub const STATE_PATH: &str = "docs/bluedb/gate-state.tsv";

const HEADER: &str =
    "# GENERATED by `cargo run -p xtask -- bluedb-gates`. DO NOT EDIT BY HAND.\n\
     # full-tier<TAB>commit<TAB>ran<TAB>host\n\
     # proof<TAB>mutation-id<TAB>outcome<TAB>commit\n";

/// The verdict `--verify-mutations` reached for one mutation (§9.4's table).
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum ProofOutcome {
    /// The patch applied and the gate went RED with the expected string.
    Proven,
    /// The patch applied and the gate stayed GREEN. For any gate but the
    /// canary this is a harness FAIL — the gate is a green lie.
    Vacuous,
    /// The patch no longer applies; the proof must be re-derived.
    MutationStale,
    /// The gate was already RED before the patch, so the patch proves nothing
    /// about it. Not specified in §9.4; see the module docs in `mutations.rs`.
    InconclusiveBaselineRed,
    /// The mutation runner detected that it was not measuring the worktree
    /// (H3). Always a harness FAIL.
    WrongTree,
}

impl ProofOutcome {
    pub fn label(self) -> &'static str {
        match self {
            ProofOutcome::Proven => "PROVEN",
            ProofOutcome::Vacuous => "VACUOUS",
            ProofOutcome::MutationStale => "MUTATION-STALE",
            ProofOutcome::InconclusiveBaselineRed => "INCONCLUSIVE-BASELINE-RED",
            ProofOutcome::WrongTree => "WRONG-TREE",
        }
    }

    pub fn parse(s: &str) -> Option<ProofOutcome> {
        Some(match s {
            "PROVEN" => ProofOutcome::Proven,
            "VACUOUS" => ProofOutcome::Vacuous,
            "MUTATION-STALE" => ProofOutcome::MutationStale,
            "INCONCLUSIVE-BASELINE-RED" => ProofOutcome::InconclusiveBaselineRed,
            "WRONG-TREE" => ProofOutcome::WrongTree,
            _ => return None,
        })
    }
}

#[derive(Clone, Debug)]
pub struct FullTierRun {
    pub commit: String,
    pub ran: String,
    pub host: String,
}

#[derive(Clone, Debug, Default)]
pub struct GateState {
    pub full_tier: Option<FullTierRun>,
    /// mutation-id -> (outcome, commit the proof was taken at)
    pub proofs: BTreeMap<String, (ProofOutcome, String)>,
}

impl GateState {
    pub fn load(root: &Path) -> GateState {
        let mut st = GateState::default();
        let Ok(text) = std::fs::read_to_string(root.join(STATE_PATH)) else {
            return st;
        };
        for line in text.lines() {
            if line.starts_with('#') || line.trim().is_empty() {
                continue;
            }
            let f: Vec<&str> = line.split('\t').collect();
            match f.as_slice() {
                ["full-tier", commit, ran, host] => {
                    st.full_tier = Some(FullTierRun {
                        commit: (*commit).to_string(),
                        ran: (*ran).to_string(),
                        host: (*host).to_string(),
                    })
                }
                ["proof", id, outcome, commit] => {
                    if let Some(o) = ProofOutcome::parse(outcome) {
                        st.proofs
                            .insert((*id).to_string(), (o, (*commit).to_string()));
                    }
                }
                _ => {}
            }
        }
        st
    }

    pub fn save(&self, root: &Path) -> std::io::Result<()> {
        let mut out = String::from(HEADER);
        if let Some(ft) = &self.full_tier {
            out.push_str(&format!(
                "full-tier\t{}\t{}\t{}\n",
                ft.commit, ft.ran, ft.host
            ));
        }
        for (id, (outcome, commit)) in &self.proofs {
            out.push_str(&format!("proof\t{}\t{}\t{}\n", id, outcome.label(), commit));
        }
        let path = root.join(STATE_PATH);
        if let Some(parent) = path.parent() {
            std::fs::create_dir_all(parent)?;
        }
        std::fs::write(path, out)
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn round_trips() {
        let dir = std::env::temp_dir().join(format!("bluedb-state-{}", std::process::id()));
        std::fs::create_dir_all(dir.join("docs/bluedb")).unwrap();

        let mut st = GateState::default();
        st.full_tier = Some(FullTierRun {
            commit: "9ece376c".into(),
            ran: "2026-08-08T22:10:04Z".into(),
            host: "linux/amd64".into(),
        });
        st.proofs.insert(
            "G0.2/rt-imports-bluedb".into(),
            (ProofOutcome::Proven, "eac3e8d2".into()),
        );
        st.proofs
            .insert("G0.C/noop".into(), (ProofOutcome::Vacuous, "eac3e8d2".into()));
        st.save(&dir).unwrap();

        let back = GateState::load(&dir);
        assert_eq!(back.full_tier.unwrap().commit, "9ece376c");
        assert_eq!(
            back.proofs["G0.2/rt-imports-bluedb"],
            (ProofOutcome::Proven, "eac3e8d2".to_string())
        );
        assert_eq!(back.proofs["G0.C/noop"].0, ProofOutcome::Vacuous);

        let _ = std::fs::remove_dir_all(&dir);
    }

    #[test]
    fn missing_file_is_an_empty_ledger_not_a_panic() {
        let st = GateState::load(Path::new("/nonexistent-bluedb-root"));
        assert!(st.full_tier.is_none());
        assert!(st.proofs.is_empty());
    }
}
