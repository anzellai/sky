//! `docs/bluedb/gate-state.tsv` — the committed, cross-run ledger.
//!
//! §9 specifies two facts that must outlive a single invocation but that
//! `STATUS.md` cannot itself carry, because `STATUS.md` is regenerated from the
//! registry on every run:
//!
//! * **the last FULL-tier run** (§9.3 property 4 — two staleness clocks). A
//!   fast run must not be able to "refresh" a status whose hard gates are weeks
//!   old, so the full-tier commit is recorded separately and only `--tier=full`
//!   updates it.
//! * **the mutation proof ledger** (§9.4 / MAJOR-17). `--verify-mutations` is
//!   too expensive for the default command, so its verdicts are recorded here
//!   and the default command renders `PROVEN @ <sha>` from the ledger —
//!   downgrading it to `UNVERIFIED-SINCE <sha>` when the mutation's declared
//!   `targets` have moved.
//!
//! Format is line-oriented TSV, not JSON, so the file is a reviewable diff and
//! the crate needs no serialisation dependency.
//!
//! ```text
//! full-tier<TAB><commit><TAB><rfc3339><TAB><host>
//! proof<TAB><mutation-id><TAB><outcome><TAB><commit>
//! ```

use std::collections::{BTreeMap, BTreeSet};
use std::path::Path;

pub const STATE_PATH: &str = "docs/bluedb/gate-state.tsv";

const HEADER: &str =
    "# GENERATED by `cargo run -p xtask -- bluedb-gates`. DO NOT EDIT BY HAND.\n\
     # full-tier<TAB>commit<TAB>ran<TAB>host\n\
     # proof<TAB>mutation-id<TAB>outcome<TAB>commit\n\
     # integrity<TAB>sha256 of every line above this one\n";

/// The seal's line prefix. Everything BEFORE this line is what it digests, so
/// the digest can never contain itself.
const INTEGRITY_PREFIX: &str = "integrity\t";

/// Was the ledger written by the harness, or by hand?
///
/// `STATUS.md` carries a `body-sha256` for exactly this reason and G0.1 checks
/// it; the ledger — which is where the word `PROVEN` actually lives — carried
/// nothing. A hand-added `proof\t<id>\tPROVEN\t<sha>` was accepted verbatim,
/// and every subsequent `--tier=full` run re-committed it.
///
/// **What the seal is, and what it is not.** It is a DETECTION, not a lock. The
/// harness rewrites the ledger on every full-tier run, so a hand edit that is
/// ignored is resealed by the next run — but not before that run's own G0.6 has
/// reported it, because the state is loaded (and the seal checked) before any
/// gate executes and long before `save` is called. A tamper is therefore
/// guaranteed at least one loud FAIL naming the file, which is one more than
/// zero. Making it a hard lock was considered and rejected: the sanctioned
/// remedy for an orphan row is to delete it by hand (see [`GateState::orphans`]
/// — the harness must never prune evidence on its own), and a lock would make
/// the sanctioned remedy indistinguishable from the attack, with an hour of
/// re-derivation as the only exit.
#[derive(Clone, PartialEq, Eq, Debug)]
pub enum Integrity {
    /// No ledger on disk. Nothing to have tampered with.
    Absent,
    /// The seal matches the bytes it covers.
    Sealed,
    /// A seal line is present and wrong.
    Broken { recorded: String, actual: String },
    /// A ledger written before the seal existed, or one whose seal was removed
    /// along with the edit. Not distinguishable from the latter, so it is
    /// reported the same way.
    Unsealed,
}

/// The verdict `--verify-mutations` reached for one mutation (§9.4's table).
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum ProofOutcome {
    /// The patch applied and the gate went RED with the expected string.
    Proven,
    /// The patch applied and the gate stayed GREEN. For any gate but the
    /// canary this is a harness FAIL — the gate is a green lie.
    Vacuous,
    /// The patch no longer applies; the proof must be re-derived.
    MutationStale,
    /// The gate was already RED before the patch, so the patch proves nothing
    /// about it. Not specified in §9.4; see the module docs in `mutations.rs`.
    InconclusiveBaselineRed,
    /// The mutation runner detected that it was not measuring the worktree
    /// (H3). Always a harness FAIL.
    WrongTree,
}

impl ProofOutcome {
    pub fn label(self) -> &'static str {
        match self {
            ProofOutcome::Proven => "PROVEN",
            ProofOutcome::Vacuous => "VACUOUS",
            ProofOutcome::MutationStale => "MUTATION-STALE",
            ProofOutcome::InconclusiveBaselineRed => "INCONCLUSIVE-BASELINE-RED",
            ProofOutcome::WrongTree => "WRONG-TREE",
        }
    }

    pub fn parse(s: &str) -> Option<ProofOutcome> {
        Some(match s {
            "PROVEN" => ProofOutcome::Proven,
            "VACUOUS" => ProofOutcome::Vacuous,
            "MUTATION-STALE" => ProofOutcome::MutationStale,
            "INCONCLUSIVE-BASELINE-RED" => ProofOutcome::InconclusiveBaselineRed,
            "WRONG-TREE" => ProofOutcome::WrongTree,
            _ => return None,
        })
    }
}

#[derive(Clone, Debug)]
pub struct FullTierRun {
    pub commit: String,
    pub ran: String,
    pub host: String,
}

#[derive(Clone, Debug)]
pub struct GateState {
    pub full_tier: Option<FullTierRun>,
    /// mutation-id -> (outcome, commit the proof was taken at)
    pub proofs: BTreeMap<String, (ProofOutcome, String)>,
    /// Whether the file this was loaded from was sealed by the harness.
    /// Freshly constructed state has nothing to check, so it is `Absent`.
    pub integrity: Integrity,
}

impl Default for GateState {
    fn default() -> GateState {
        GateState {
            full_tier: None,
            proofs: BTreeMap::new(),
            integrity: Integrity::Absent,
        }
    }
}

/// Split a ledger into (the sealed region, the recorded digest).
fn split_seal(text: &str) -> Option<(&str, String)> {
    let at = text.rfind(&format!("\n{INTEGRITY_PREFIX}"))?;
    let recorded = text[at + 1 + INTEGRITY_PREFIX.len()..].trim().to_string();
    Some((&text[..at + 1], recorded))
}

impl GateState {
    pub fn load(root: &Path) -> GateState {
        let mut st = GateState::default();
        let Ok(text) = std::fs::read_to_string(root.join(STATE_PATH)) else {
            return st;
        };
        st.integrity = match split_seal(&text) {
            None => Integrity::Unsealed,
            Some((region, recorded)) => {
                let actual = super::sha256::hex(region.as_bytes());
                if actual == recorded {
                    Integrity::Sealed
                } else {
                    Integrity::Broken { recorded, actual }
                }
            }
        };
        for line in text.lines() {
            if line.starts_with('#') || line.trim().is_empty() {
                continue;
            }
            let f: Vec<&str> = line.split('\t').collect();
            match f.as_slice() {
                ["full-tier", commit, ran, host] => {
                    st.full_tier = Some(FullTierRun {
                        commit: (*commit).to_string(),
                        ran: (*ran).to_string(),
                        host: (*host).to_string(),
                    })
                }
                ["proof", id, outcome, commit] => {
                    if let Some(o) = ProofOutcome::parse(outcome) {
                        st.proofs
                            .insert((*id).to_string(), (o, (*commit).to_string()));
                    }
                }
                _ => {}
            }
        }
        st
    }

    pub fn save(&self, root: &Path) -> std::io::Result<()> {
        let mut out = String::from(HEADER);
        if let Some(ft) = &self.full_tier {
            out.push_str(&format!(
                "full-tier\t{}\t{}\t{}\n",
                ft.commit, ft.ran, ft.host
            ));
        }
        for (id, (outcome, commit)) in &self.proofs {
            out.push_str(&format!("proof\t{}\t{}\t{}\n", id, outcome.label(), commit));
        }
        out.push_str(&format!(
            "{INTEGRITY_PREFIX}{}\n",
            super::sha256::hex(out.as_bytes())
        ));
        let path = root.join(STATE_PATH);
        if let Some(parent) = path.parent() {
            std::fs::create_dir_all(parent)?;
        }
        std::fs::write(path, out)
    }

    /// Rows recording a proof for a mutation id **no gate declares**.
    ///
    /// # Why they exist, and why nothing may quietly remove them
    ///
    /// `verify_all` is load → insert → save: it has never had a `remove` or a
    /// `retain`, and no reader has ever iterated `proofs` looking for a row
    /// nothing references. `G0.6` iterates the REGISTRY and uses the ledger as a
    /// lookup table, so a row with no registry entry is invisible to it. Retire
    /// a mutation id — rename it, re-cut a gate, drop one of a gate's two
    /// mutations (a gate needs only one) — and its `PROVEN` survives: never
    /// checked, never rendered, and re-committed by every full-tier run.
    /// Re-register that id later and the stale row is read as a current proof
    /// that was never re-derived. One was found by hand in this ledger.
    ///
    /// The obvious fix — prune on save — is the wrong one, and it is worth
    /// being explicit about why: pruning makes DELETING A PATCH FILE a way to
    /// silence a `PROVEN`. Today that is a FAIL ("the ledger records a proof but
    /// the patch is gone"); under an auto-pruning ledger it would be a no-op
    /// that leaves a green tree. The harness must never destroy its own evidence
    /// as a side effect of running.
    ///
    /// So this REPORTS, and both callers fail on a non-empty result:
    /// `--verify-mutations` refuses to finish, and G0.6 records a finding. The
    /// remedy is a human deleting the row — a one-line reviewable diff, which
    /// breaks the seal ([`Integrity`]) and so is itself reported once. There is
    /// deliberately no `--prune-orphans` verb: a tool whose whole function is to
    /// remove proof rows is the tool an attacker wants, and the operation it
    /// would automate is one line of a text file.
    pub fn orphans<'a>(&self, registered: impl IntoIterator<Item = &'a str>) -> Vec<String> {
        let known: BTreeSet<&str> = registered.into_iter().collect();
        self.proofs
            .keys()
            .filter(|id| !known.contains(id.as_str()))
            .cloned()
            .collect()
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn round_trips() {
        let dir = std::env::temp_dir().join(format!("bluedb-state-{}", std::process::id()));
        std::fs::create_dir_all(dir.join("docs/bluedb")).unwrap();

        let mut st = GateState::default();
        st.full_tier = Some(FullTierRun {
            commit: "9ece376c".into(),
            ran: "2026-08-08T22:10:04Z".into(),
            host: "linux/amd64".into(),
        });
        st.proofs.insert(
            "G0.2/rt-imports-bluedb".into(),
            (ProofOutcome::Proven, "eac3e8d2".into()),
        );
        st.proofs
            .insert("G0.C/noop".into(), (ProofOutcome::Vacuous, "eac3e8d2".into()));
        st.save(&dir).unwrap();

        let back = GateState::load(&dir);
        assert_eq!(back.full_tier.unwrap().commit, "9ece376c");
        assert_eq!(
            back.proofs["G0.2/rt-imports-bluedb"],
            (ProofOutcome::Proven, "eac3e8d2".to_string())
        );
        assert_eq!(back.proofs["G0.C/noop"].0, ProofOutcome::Vacuous);

        let _ = std::fs::remove_dir_all(&dir);
    }

    /// The row nothing references. Retiring an id used to leave its `PROVEN`
    /// behind: checked by nothing, rendered by nothing, re-committed by every
    /// run, and readable as a current proof the day the id is re-registered.
    #[test]
    fn a_row_no_gate_declares_is_reported_and_not_removed() {
        let mut st = GateState::default();
        st.proofs.insert(
            "G9.9/retired".into(),
            (ProofOutcome::Proven, "deadbeef".into()),
        );
        st.proofs.insert(
            "G0.2/rt-imports-bluedb".into(),
            (ProofOutcome::Proven, "eac3e8d2".into()),
        );

        assert_eq!(
            st.orphans(["G0.2/rt-imports-bluedb"]),
            vec!["G9.9/retired".to_string()]
        );
        // Reporting must not be pruning: the caller decides, and the evidence
        // survives the call. An auto-pruning ledger would make deleting a patch
        // file a way to turn a FAIL into a green tree.
        assert!(st.proofs.contains_key("G9.9/retired"));
        // A registered id is never an orphan, whatever its outcome.
        assert!(st
            .orphans(["G0.2/rt-imports-bluedb", "G9.9/retired"])
            .is_empty());
    }

    /// The seal is over the rows, and it travels with them.
    #[test]
    fn the_ledger_is_sealed_on_save_and_a_hand_edit_breaks_it() {
        let dir = std::env::temp_dir().join(format!("bluedb-seal-{}", std::process::id()));
        std::fs::create_dir_all(dir.join("docs/bluedb")).unwrap();

        let mut st = GateState::default();
        st.proofs.insert(
            "G0.2/rt-imports-bluedb".into(),
            (ProofOutcome::Proven, "eac3e8d2".into()),
        );
        st.save(&dir).unwrap();
        assert_eq!(GateState::load(&dir).integrity, Integrity::Sealed);

        // The forgery the seal exists for: a `PROVEN` nobody derived.
        let path = dir.join(STATE_PATH);
        let text = std::fs::read_to_string(&path).unwrap();
        let forged = text.replace(
            "proof\tG0.2",
            "proof\tG9.9/never-ran\tPROVEN\tdeadbeef\nproof\tG0.2",
        );
        std::fs::write(&path, forged).unwrap();
        let back = GateState::load(&dir);
        assert!(matches!(back.integrity, Integrity::Broken { .. }));
        // …and the rows still parse, so the tamper is REPORTED rather than
        // swallowing the ledger with it.
        assert!(back.proofs.contains_key("G9.9/never-ran"));

        // A ledger written before the seal existed is not silently accepted.
        std::fs::write(&path, "proof\tG0.2/x\tPROVEN\tabc\n").unwrap();
        assert_eq!(GateState::load(&dir).integrity, Integrity::Unsealed);

        let _ = std::fs::remove_dir_all(&dir);
    }

    #[test]
    fn missing_file_is_an_empty_ledger_not_a_panic() {
        let st = GateState::load(Path::new("/nonexistent-bluedb-root"));
        assert!(st.full_tier.is_none());
        assert!(st.proofs.is_empty());
    }
}
