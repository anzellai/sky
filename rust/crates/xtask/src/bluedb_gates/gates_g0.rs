// G0.5 — the single go-build site carries the zstd tag
// ---------------------------------------------------------------------------

const ZSTD_TAG: &str = "pebblegozstd";

/// The symbol fragment that means the **cgo** DataDog codec got linked. Pebble
/// selects `github.com/DataDog/zstd` unless `pebblegozstd` picks klauspost's
/// pure-Go one, and Go mangles the module path into the symbol name, so a
/// linked DataDog codec is visible to `go tool nm`.
const DATADOG_ZSTD: &str = "datadog/zstd";

const G0_5_BUILD_BUDGET: Duration = Duration::from_secs(360);

/// Arm (a) — **every** `go build` site in the compiler carries the tag — is
/// asserted unconditionally, and is the arm the declared mutation ("add an
/// untagged site") falsifies.
///
/// # Why the invariant is "every site", and no longer "exactly one site"
///
/// It used to assert that `rust/crates/project/src` held exactly one `go build`
/// and that that one carried the tag. Both halves were wrong at once. There are
/// **three** compiler sites — the app build (`project::build`), the hub build
/// (`sky::main`, `cmd/sky-hub` inside `runtime-go/`) and the inspector build
/// (`ffi::inspect`, `sky-ffi-inspect`) — plus the gate's own cgo re-link below.
/// Two of the three shipped with no `-tags` at all, and neither was visible to
/// the scan.
///
/// "Exactly one site" is therefore false against correct code, and its declared
/// mutation ("add a second site") is satisfied by real shipped code. The
/// invariant that survives the correction is the one the property was always
/// about: *every* site carries the tag, however many there are. Counting sites
/// was only ever a proxy for it.
///
/// The tag check is unconditional, where it used to be gated on
/// `runtime-go/go.mod` requiring pebble. It is a SOURCE-level contract about the
/// argv, not a claim about today's import graph — the hub's own docstring makes
/// exactly that argument for tagging a site pebble does not currently reach —
/// and a check that switches itself off cannot catch the site that gets added
/// while it is off.
///
/// Arm (c) — `go tool nm` finds no DataDog cgo zstd symbols in a real Persist
/// binary — IS still conditional on pebble being in the module graph, because
/// there are no symbols to look for otherwise. That condition is read from
/// `go.mod`, not chosen by the gate author, and it ratchets.
pub fn g0_5_zstd_tag(ctx: &Ctx) -> GateOutcome {
    let mut findings = Vec::new();

    let scan = go_build_sites(ctx);

    // The vacuity floor. "0 of 0 sites are untagged" is a green lie, and it is
    // the shape a broken scan (a moved crate root, a renamed `Command::new`)
    // takes — indistinguishable from a clean tree without this.
    if scan.sites.is_empty() {
        findings.push(format!(
            "no `go build` site found in any of the {} crate source trees under rust/crates — \
             the compiler certainly runs `go build`, so the scan is broken and certifies nothing",
            scan.roots
        ));
    }

    // The constants that carry the tag, over the UNION of every scanned file.
    //
    // Per-file was wrong and silently so: `rust/crates/sky/src/main.rs` writes
    // `.args(project::GO_BUILD_TAG_ARGS)` and declares neither constant, so a
    // per-file derivation returned two empty lists and reported the site as
    // UNTAGGED — a gate red on correct code, which is how a widened scan gets
    // narrowed again.
    let universe = tag_carrying_consts(
        &scan
            .texts
            .values()
            .map(String::as_str)
            .collect::<Vec<_>>()
            .join("\n"),
    );

    for (file, line) in &scan.sites {
        let text = scan.texts.get(file).map(String::as_str).unwrap_or_default();
        if !zstd_tag_reaches_site(text, *line, &universe) {
            findings.push(format!(
                "go build site {file}:{line} does not carry `-tags {ZSTD_TAG}` — that build links \
                 pebble's cgo DataDog zstd while every other build of the same tree links pure-Go \
                 klauspost, and only one of the two is ever the one that was tested"
            ));
        }
    }

    let pebble_present = ctx
        .read("runtime-go/go.mod")
        .map(|m| m.contains("cockroachdb/pebble"))
        .unwrap_or(false);

    let mut arm_c = "not applicable — runtime-go/go.mod does not require pebble yet".to_string();
    if pebble_present {
        match g0_5_arm_c(ctx) {
            Ok(detail) => arm_c = detail,
            Err(finding) => findings.push(finding),
        }
    }

    if findings.is_empty() {
        GateOutcome::pass(format!(
            "{} `go build` site(s) over {} crate source trees, every one carrying `-tags {ZSTD_TAG}` \
             ({}) [tier {}]; arm (c): {arm_c}",
            scan.sites.len(),
            scan.roots,
            scan.sites
                .iter()
                .map(|(f, l)| format!("{f}:{l}"))
                .collect::<Vec<_>>()
                .join(", "),
            ctx.tier.label()
        ))
    } else {
        GateOutcome::fail("go-build site / zstd tag contract broken", findings)
    }
}

/// Arm (b): the tag reaches the **invocation**, not merely the file.
///
/// `build_rs.contains("pebblegozstd")` was the original spelling and is no
/// longer sufficient — the constant's declaration, its doc comment and its unit
/// test all mention the string, so deleting `-tags` from the argv would leave a
/// whole-file `contains` green while every shipped binary changed what it
/// links. That is a gate weakened by the very commit that implemented the
/// property, which is the failure mode this harness is named after.
///
/// So the check is scoped to the argument list at `site_line`, following the
/// one level of const indirection the compiler actually uses
/// (`.args(GO_BUILD_TAG_ARGS)` where `GO_BUILD_TAG_ARGS = ["-tags",
/// GO_BUILD_ZSTD_TAG]`). Indirection is resolved from the source, not
/// hard-coded: a rename of either constant keeps working, and deleting the
/// argument does not.
///
/// # `universe`, and the trap that makes it necessary
///
/// The constant names come from the caller as the union over EVERY scanned
/// file, not from `src`. A site does not have to declare the constant it uses:
/// `rust/crates/sky/src/main.rs` writes `.args(project::GO_BUILD_TAG_ARGS)`,
/// declares neither `GO_BUILD_ZSTD_TAG` nor `GO_BUILD_TAG_ARGS`, and contains
/// neither the literal `pebblegozstd` nor `-tags` anywhere `const_name` would
/// accept. Deriving the names from `src` alone therefore returned two empty
/// lists and called that site untagged — a widened scan going red on correct
/// code, which is how a widened scan gets narrowed back again.
///
/// The window is comment-stripped for the same reason the body text is: a
/// docstring naming `GO_BUILD_TAG_ARGS` above the argv is a mention, not a flag.
fn zstd_tag_reaches_site(
    src: &str,
    site_line: usize,
    universe: &(Vec<String>, Vec<String>),
) -> bool {
    let lines: Vec<&str> = src.lines().collect();
    let start = site_line.saturating_sub(1);
    let window: String = lines[start..(start + 14).min(lines.len())]
        .iter()
        .map(|l| match l.find("//") {
            Some(p) => &l[..p],
            None => l,
        })
        .collect::<Vec<_>>()
        .join("\n");

    let (holds_tag, tag_args) = universe;

    // `.arg("-tags").arg(<the tag, literal or by name>)`
    if window.contains("-tags")
        && (window.contains(ZSTD_TAG) || holds_tag.iter().any(|n| window.contains(n.as_str())))
    {
        return true;
    }
    // `.args(<a const that IS the -tags pair>)`
    tag_args.iter().any(|name| window.contains(name.as_str()))
}

/// The constants in `src` that carry the tag, as
/// `(holds-the-tag, is-the-whole-"-tags"-pair)`.
///
/// Two lists because the compiler spells it in two levels: `GO_BUILD_ZSTD_TAG`
/// holds the tag string, `GO_BUILD_TAG_ARGS` holds `["-tags",
/// GO_BUILD_ZSTD_TAG]`.
fn tag_carrying_consts(src: &str) -> (Vec<String>, Vec<String>) {
    let mut holds_tag: Vec<String> = Vec::new();
    for line in src.lines() {
        if line.contains(ZSTD_TAG) {
            if let Some(n) = const_name(line) {
                holds_tag.push(n);
            }
        }
    }
    let mut pairs: Vec<String> = Vec::new();
    for line in src.lines() {
        if !line.contains("-tags") {
            continue;
        }
        let carries =
            line.contains(ZSTD_TAG) || holds_tag.iter().any(|n| line.contains(n.as_str()));
        if !carries {
            continue;
        }
        if let Some(n) = const_name(line) {
            pairs.push(n);
        }
    }
    (holds_tag, pairs)
}

/// `pub const NAME: T = …` / `const NAME: T = …` -> `NAME`.
fn const_name(line: &str) -> Option<String> {
    let pos = line.find("const ")?;
    let rest = &line[pos + "const ".len()..];
    let end = rest.find(|c: char| !(c.is_ascii_alphanumeric() || c == '_'))?;
    let name = &rest[..end];
    if name.is_empty() {
        None
    } else {
        Some(name.to_string())
    }
}

/// Arm (c): **a Persist binary contains no DataDog cgo zstd symbols**, on every
/// one of the three call paths.
///
/// `Ok(detail)` is the arm asserted; `Err(finding)` is the arm NOT asserted,
/// which is a FAIL and never a quiet pass — an arm nobody ran is the exact
/// shape of the green lie this harness exists to catch.
///
/// # How three paths are covered by two builds
///
/// The three call paths into `run_go_build_once` (webview CGO=1, static CGO=0,
/// cgo retry CGO=1) differ in **`CGO_ENABLED` and nothing else** — same argv,
/// same site (§7.2). So the arm builds the Persist witness through the compiler
/// (which takes the CGO=0 static path for a pure-Go app), then re-links the very
/// same emitted `sky-out/` with `CGO_ENABLED=1` using
/// [`project::GO_BUILD_TAG_ARGS`] — the compiler's OWN flag constant, not a
/// hand-copied duplicate. That coupling is deliberate: an edit that drops the
/// tag from the compiler drops it from this re-link too, and the cgo build then
/// really does pull the DataDog codec, so the arm goes red for the true reason
/// instead of quietly re-deriving the flag it was supposed to be checking.
///
/// # The vacuity guard
///
/// "no DataDog zstd symbols" is trivially true of a binary that links no pebble
/// at all. The arm therefore FAILS unless it first sees pebble symbols in the
/// witness. Without that, the arm would go green the day the Persist example
/// stopped using Persist.
fn g0_5_arm_c(ctx: &Ctx) -> Result<String, String> {
    let Some(sky) = sky_compiler(ctx) else {
        return Err(format!(
            "arm (c) NOT VERIFIED: no compiler at {}/rust/target/release/sky or sky-out/sky — \
             build it first (cd rust && cargo build --release -p sky)",
            ctx.root().display()
        ));
    };
    let Some(witness) = persist_witness(ctx) else {
        // No project imports `Std.Persist`, so "a Persist binary carries no
        // DataDog zstd" is quantified over the EMPTY SET. Reported as that
        // rather than asserted — the same treatment G0.2 gives its `bluedb`
        // arm, and the same reason G0.3 reports NOT RUN: a claim with no
        // instances is not evidence.
        //
        // It is still a ratchet, because the condition is machine-decided and
        // the moment the API ships it stops being satisfiable this way: once
        // `sky-stdlib/Std/Persist.sky` exists, a tree with NO Persist project
        // is a real gap in the corpus and becomes a finding below.
        if ctx.exists("sky-stdlib/Std/Persist.sky") {
            return Err(
                "arm (c) NOT VERIFIED: sky-stdlib/Std/Persist.sky exists, so Persist binaries are \
                 buildable, but no project under examples/ imports Std.Persist — there is nothing \
                 to run `go tool nm` over. Ship the Persist example with the API."
                    .to_string(),
            );
        }
        return Ok(
            "quantified over an empty set — no project imports Std.Persist and \
             sky-stdlib/Std/Persist.sky does not exist yet; the arm runs on the first Persist project"
                .to_string(),
        );
    };

    let scratch = Scratch::create("g0.5").map_err(|e| format!("arm (c) NOT VERIFIED: {e}"))?;
    let env = offline_build_env(&scratch.dir);
    let dir = ctx.path(&witness);
    let built = build_project(&sky, &dir, &env.vars, G0_5_BUILD_BUDGET)
        .map_err(|e| format!("arm (c) NOT VERIFIED: the Persist witness {witness} did not build: {e}"))?;

    let mut checked = Vec::new();
    for (label, binary) in [
        ("CGO_ENABLED=0 (the static path)".to_string(), built.binary.clone()),
        (
            "CGO_ENABLED=1 (the webview + retry paths)".to_string(),
            relink_with_cgo(&built.out_dir, &env.vars, G0_5_BUILD_BUDGET)
                .map_err(|e| format!("arm (c) NOT VERIFIED: {e}"))?,
        ),
    ] {
        let syms = nm_symbols(&binary, G0_3_NM_BUDGET)
            .map_err(|e| format!("arm (c) NOT VERIFIED on {label}: {e}"))?;
        let lowered: Vec<String> = syms.iter().map(|s| s.to_ascii_lowercase()).collect();

        if !lowered.iter().any(|s| s.contains("pebble")) {
            return Err(format!(
                "arm (c) NOT VERIFIED on {label}: the Persist witness {witness} linked NO pebble \
                 symbols, so \"no DataDog zstd\" would be true of an empty set"
            ));
        }
        let hits: Vec<&String> = lowered
            .iter()
            .filter(|s| s.contains(DATADOG_ZSTD))
            .collect();
        if !hits.is_empty() {
            return Err(format!(
                "arm (c): DataDog cgo zstd symbols in a Persist binary on {label} — {} matches, e.g. {}; \
                 `-tags {ZSTD_TAG}` did not reach this build",
                hits.len(),
                hits.iter().take(3).map(|s| s.as_str()).collect::<Vec<_>>().join(", ")
            ));
        }
        checked.push(format!("{label}: {} symbols, 0 DataDog zstd", syms.len()));
    }

    Ok(format!("{witness} — {}", checked.join("; ")))
}

/// Re-link an already-emitted `sky-out/` with `CGO_ENABLED=1`, using the
/// compiler's own build tags. Returns the path of the new binary.
fn relink_with_cgo(
    out_dir: &Path,
    env: &[(String, String)],
    budget: Duration,
) -> Result<PathBuf, String> {
    let bin = out_dir.join("app-cgo1");
    let mut cmd = Command::new("go");
    cmd.arg("build")
        .args(project::GO_BUILD_TAG_ARGS)
        .arg("-o")
        .arg(&bin)
        .arg(".")
        .current_dir(out_dir)
        .env("CGO_ENABLED", "1");
    for (k, v) in env {
        cmd.env(k, v);
    }
    let run = capped(cmd, budget).map_err(|e| format!("the CGO_ENABLED=1 re-link: {e}"))?;
    if run.timed_out {
        return Err(format!(
            "the CGO_ENABLED=1 re-link exceeded {}s and its process group was killed",
            budget.as_secs()
        ));
    }
    if !run.ok {
        return Err(format!(
            "the CGO_ENABLED=1 re-link failed in {}:\n{}",
            out_dir.display(),
            layer2::tail(&run.out, 30)
        ));
    }
    Ok(bin)
}

/// The first project under `examples/` whose Sky source imports `Std.Persist`,
/// as a repo-relative path. `None` means arm (c) has no subject, which the
/// caller reports rather than skips.
fn persist_witness(ctx: &Ctx) -> Option<String> {
    let rd = std::fs::read_dir(ctx.path("examples")).ok()?;
    let mut dirs: Vec<PathBuf> = rd.filter_map(|e| e.ok().map(|e| e.path())).collect();
    dirs.sort();
    for d in dirs {
        if !d.join("sky.toml").is_file() {
            continue;
        }
        if persist_imports_of(&d)
            .iter()
            .any(|c| c.contains("Std.Persist"))
        {
            return Some(rel(ctx, &d));
        }
    }
    None
}

/// Every `go build` site the compiler workspace contains, plus the text of every
/// file scanned to find them.
pub struct GoBuildScan {
    /// `(repo-relative file, 1-based line)` of each `Command::new("go")` whose
    /// command line contains `build`.
    pub sites: Vec<(String, usize)>,
    /// Every scanned file's text, keyed by the same repo-relative path. Kept
    /// because the tag check needs BOTH the site's own file (for the argv
    /// window) and the union of all of them (for the constant the site
    /// references but does not declare) — see [`zstd_tag_reaches_site`].
    pub texts: BTreeMap<String, String>,
    /// How many `<crate>/src` trees were walked. Rendered into the PASS detail:
    /// a scan that walked nothing would otherwise report "0 untagged sites".
    pub roots: usize,
}

/// A `Command::new("go")` whose command line contains `build` within the next
/// few lines. `go get` / `go tool` sites are not `go build` sites.
///
/// # The scope, and why it is not a curated list
///
/// This read `rust/crates/project/src` **only**, on the belief — written into
/// `GO_BUILD_ZSTD_TAG`'s own docstring — that `run_go_build_once` was "the ONLY
/// `go build` invocation in the compiler". It was not, and the gate that exists
/// to catch exactly that could not see the counter-example:
/// `rust/crates/sky/src/main.rs` builds `cmd/sky-hub` inside `runtime-go/` and
/// shipped with no `-tags` at all, and widening the scan then found a third at
/// `rust/crates/ffi/src/inspect.rs` (`sky-ffi-inspect`) in the same state.
///
/// So the roots are enumerated from the filesystem — every `<crate>/src` under
/// `rust/crates` — rather than listed by an author. A new crate that shells out
/// to `go build` is in scope the day it is created, and a scope this gate cannot
/// see is a scope a future site can hide in.
fn go_build_sites(ctx: &Ctx) -> GoBuildScan {
    let mut sites = Vec::new();
    let mut texts = BTreeMap::new();
    let mut roots = 0usize;

    let mut crate_dirs: Vec<PathBuf> = match std::fs::read_dir(ctx.path("rust/crates")) {
        Ok(rd) => rd
            .flatten()
            .map(|e| e.path())
            .filter(|p| p.join("src").is_dir())
            .collect(),
        Err(_) => Vec::new(),
    };
    crate_dirs.sort();

    for c in crate_dirs {
        roots += 1;
        for f in collect_ext(&c.join("src"), "rs") {
            let Ok(text) = std::fs::read_to_string(&f) else {
                continue;
            };
            let path = rel(ctx, &f);
            let lines: Vec<&str> = text.lines().collect();
            for (i, line) in lines.iter().enumerate() {
                if !line.contains("Command::new(\"go\")") {
                    continue;
                }
                let window = lines[i..(i + 6).min(lines.len())].join(" ");
                if window.contains(".arg(\"build\")") || window.contains("\"build\",") {
                    sites.push((path.clone(), i + 1));
                }
            }
            texts.insert(path, text);
        }
    }

    sites.sort();
    GoBuildScan {
        sites,
        texts,
        roots,
    }
}

