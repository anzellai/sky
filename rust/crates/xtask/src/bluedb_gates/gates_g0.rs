// G0.5 — the single go-build site carries the zstd tag
// ---------------------------------------------------------------------------

const ZSTD_TAG: &str = "pebblegozstd";

/// Arm (a) — `run_go_build_once` is the sole `go build` site — is asserted
/// unconditionally, and is the arm the declared mutation ("add a second site")
/// falsifies.
///
/// Arms (b) `-tags pebblegozstd` and (c) `go tool nm` finds no DataDog cgo zstd
/// symbols are asserted **iff `runtime-go/go.mod` requires pebble**. The tag
/// selects pebble's pure-Go zstd implementation; with no pebble in the module
/// graph it selects nothing, and asserting it would be theatre. The condition is
/// read from `go.mod`, not chosen by the gate author, and it ratchets: the
/// commit that adds pebble turns arms (b)/(c) live.
pub fn g0_5_zstd_tag(ctx: &Ctx) -> GateOutcome {
    let mut findings = Vec::new();

    let sites = go_build_sites(ctx);
    if sites.len() != 1 {
        findings.push(format!(
            "expected exactly 1 `go build` site in rust/crates/project/src, found {}: {}",
            sites.len(),
            sites
                .iter()
                .map(|(f, l)| format!("{f}:{l}"))
                .collect::<Vec<_>>()
                .join(", ")
        ));
    }

    let pebble_present = ctx
        .read("runtime-go/go.mod")
        .map(|m| m.contains("cockroachdb/pebble"))
        .unwrap_or(false);

    let build_rs = ctx.read("rust/crates/project/src/build.rs").unwrap_or_default();
    let tag_present = build_rs.contains(ZSTD_TAG);

    if pebble_present {
        if !tag_present {
            findings.push(format!(
                "runtime-go/go.mod requires pebble but no `-tags {ZSTD_TAG}` appears at the go build site — CI would link the cgo DataDog zstd while shipped apps link pure-Go klauspost"
            ));
        }
        findings.push(
            "arm (c) (`go tool nm` finds no DataDog cgo zstd symbols in a Persist binary) is not implemented, and pebble has landed — implement it with P1".into(),
        );
    }

    if findings.is_empty() {
        let arm_bc = if pebble_present {
            "asserted"
        } else {
            "not applicable — runtime-go/go.mod does not require pebble yet"
        };
        GateOutcome::pass(format!(
            "1 `go build` site ({}) [tier {}]; arms (b)/(c): {arm_bc}",
            sites
                .first()
                .map(|(f, l)| format!("{f}:{l}"))
                .unwrap_or_default(),
            ctx.tier.label()
        ))
    } else {
        GateOutcome::fail("go-build site / zstd tag contract broken", findings)
    }
}

/// A `Command::new("go")` whose command line contains `build` within the next
/// few lines. `go get` / `go tool` sites are not `go build` sites.
fn go_build_sites(ctx: &Ctx) -> Vec<(String, usize)> {
    let mut out = Vec::new();
    for f in collect_ext(&ctx.path("rust/crates/project/src"), "rs") {
        let Ok(text) = std::fs::read_to_string(&f) else {
            continue;
        };
        let lines: Vec<&str> = text.lines().collect();
        for (i, line) in lines.iter().enumerate() {
            if !line.contains("Command::new(\"go\")") {
                continue;
            }
            let window = lines[i..(i + 6).min(lines.len())].join(" ");
            if window.contains(".arg(\"build\")") || window.contains("\"build\",") {
                out.push((rel(ctx, &f), i + 1));
            }
        }
    }
    out
}

// ---------------------------------------------------------------------------
// G0.6 — every recorded mutation proof is present and current
// ---------------------------------------------------------------------------

/// `--verify-mutations` is the expensive re-derivation; G0.6 is the cheap
/// standing assertion that its results exist, cover every mutation of every
/// implemented gate, carry the expected RED output, and have not decayed.
pub fn g0_6_mutations_verified(ctx: &Ctx) -> GateOutcome {
    let state = GateState::load(ctx.root());
    let mut findings = Vec::new();
    let mut unauthored = 0usize;

    for gate in REGISTRY {
        for m in gate.mutations.as_slice() {
            let patch = ctx.path(m.patch);
            if !patch.exists() {
                if state.proofs.contains_key(m.id) {
                    findings.push(format!(
                        "{}: the ledger records a proof but the patch at {} is gone",
                        m.id, m.patch
                    ));
                } else {
                    // The gate is not authored yet. It already renders NOT RUN,
                    // which renders its goal UNKNOWN, so counting it here would
                    // drown the real findings without adding any signal. An
                    // *implemented* gate with no patch cannot hide this way:
                    // `--verify-mutations` records MUTATION-STALE for it, and
                    // that lands in the ledger and is caught below.
                    unauthored += 1;
                }
                continue;
            }
            let Some((outcome, sha)) = state.proofs.get(m.id) else {
                findings.push(format!(
                    "{}: recorded proof ledger is stale — no entry in {}",
                    m.id,
                    super::state::STATE_PATH
                ));
                continue;
            };
            let want = if gate.id == super::registry::CANARY_ID {
                ProofOutcome::Vacuous
            } else {
                ProofOutcome::Proven
            };
            if *outcome != want {
                findings.push(format!(
                    "{}: recorded {} but {} is required",
                    m.id,
                    outcome.label(),
                    want.label()
                ));
                continue;
            }
            // The canary declares `<never>`: it cannot go red, so there is no
            // RED output to record. Requiring one would be requiring evidence
            // the design says must not exist.
            if m.expect != "<never>" {
                let expected_file = expected_path(m.patch);
                match std::fs::read_to_string(ctx.path(&expected_file)) {
                    Err(_) => findings.push(format!(
                        "{}: recorded proof ledger is stale — no expected output at {expected_file}",
                        m.id
                    )),
                    Ok(text) => {
                        if !text.contains(m.expect) {
                            findings.push(format!(
                                "{}: recorded expected output does not contain the declared assertion {:?}",
                                m.id, m.expect
                            ));
                        }
                    }
                }
            }
            if super::mutations::targets_moved(ctx.root(), sha, m.targets) {
                findings.push(format!(
                    "{}: UNVERIFIED-SINCE {sha} — a declared target moved",
                    m.id
                ));
            }
        }
    }

    if findings.is_empty() {
        GateOutcome::pass(format!(
            "every authored mutation carries a current proof ({unauthored} not authored yet)"
        ))
    } else {
        GateOutcome::fail(
            format!(
                "{} mutation proof problem(s) ({unauthored} not authored yet)",
                findings.len()
            ),
            findings,
        )
    }
}

pub fn expected_path(patch: &str) -> String {
    patch
        .strip_suffix(".patch")
        .map(|s| format!("{s}.expected.txt"))
        .unwrap_or_else(|| format!("{patch}.expected.txt"))
}

// ---------------------------------------------------------------------------
// G0.7 — harness self-integrity + citation resolution
// ---------------------------------------------------------------------------

pub fn g0_7_self_integrity(ctx: &Ctx) -> GateOutcome {
    let mut findings = static_checks();

    let (cite_findings, cite_warnings, cite_total) = check_citations(ctx);
    findings.extend(cite_findings);

    // §9.6: a moved line is a warning, not a failure — surfaced on demand so a
    // signal that always fires never drowns the ones that matter.
    if ctx.verbose {
        for w in &cite_warnings {
            println!("  warn: {w}");
        }
    }

    if findings.is_empty() {
        GateOutcome::pass(format!(
            "3 static checks green over {} gates; {cite_total} citations resolved ({} warning(s))",
            REGISTRY.len(),
            cite_warnings.len()
        ))
    } else {
        GateOutcome::fail(
            format!("{} self-integrity finding(s)", findings.len()),
            findings,
        )
    }
}

/// §9.6's three checks. Run standalone by [`super::run`] before any gate
/// executes, and again inside G0.7 so the property is both a precondition and a
/// reported gate.
pub fn static_checks() -> Vec<String> {
    let mut findings = Vec::new();

    // 1. every goal 1..=5 owns at least one gate
    for goal in 1..=5u8 {
        if !REGISTRY.iter().any(|g| g.goal == goal) {
            findings.push(format!(
                "static check 1: goal {goal} has no gate — a goal with no gate is a FAIL, not an omission"
            ));
        }
    }

    // 2. every gate maps to exactly one goal, or is explicitly cross-cutting
    for g in REGISTRY {
        if g.goal > 5 {
            findings.push(format!(
                "static check 2: gate {} declares goal {} — must be 0 (cross-cutting) or 1..=5",
                g.id, g.goal
            ));
        }
    }

    // 3. every gate declares at least one mutation (H1's runtime backstop
    //    behind `Mutations::new`'s const-eval assertion)
    for g in REGISTRY {
        if g.mutations.is_empty() {
            findings.push(format!(
                "static check 3: gate {} declares no mutation — UNPROVEN, and its goal FAILs",
                g.id
            ));
        }
    }

    findings
}

/// Which tree a citation tag resolves against (the Citation provenance block).
fn tag_branch(tag: &str) -> Option<&'static str> {
    Some(match tag {
        "main" => "HEAD",
        "bdb" => "feat/bluedb",
        "p5e" => "salvage/p5e-foundation",
        "exp" => "exp/bluedb",
        _ => return None,
    })
}

pub struct Citation {
    pub line_no: usize,
    pub tag: Option<String>,
    pub path: String,
    pub line: usize,
    pub token: Option<String>,
}

/// Parse every `` `path:line` `` citation out of the architecture doc, together
/// with the branch tag governing it (the nearest `[main]`/`[bdb]`/`[p5e]`/`[exp]`
/// marker earlier on the same line) and the backticked identifier immediately
/// preceding it, if any.
pub fn parse_citations(doc: &str) -> Vec<Citation> {
    let mut out = Vec::new();
    let mut in_fence = false;
    for (i, line) in doc.lines().enumerate() {
        // Fenced blocks are illustrations — the §9.3 `STATUS.md` sample, the
        // §9.2 struct sketches — not claims about the code. Checking them would
        // report the example's invented `committer.go:214` as a stale citation.
        if line.trim_start().starts_with("```") {
            in_fence = !in_fence;
            continue;
        }
        if in_fence {
            continue;
        }
        for (col, path, lineno) in find_path_line_pairs(line) {
            let head = &line[..col];
            let tag = ["main", "bdb", "p5e", "exp"]
                .iter()
                .filter_map(|t| head.rfind(&format!("[{t}]")).map(|p| (p, (*t).to_string())))
                .max_by_key(|(p, _)| *p)
                .map(|(_, t)| t);
            out.push(Citation {
                line_no: i + 1,
                tag,
                path,
                line: lineno,
                token: preceding_backticked_ident(head),
            });
        }
    }
    out
}

/// Returns `(byte offset, path, line)` for every `path.ext:NNN` in `line`.
fn find_path_line_pairs(line: &str) -> Vec<(usize, String, usize)> {
    const EXTS: &[&str] = &[
        ".go", ".rs", ".sky", ".skyi", ".yml", ".yaml", ".md", ".toml", ".json",
    ];
    let bytes = line.as_bytes();
    let mut out = Vec::new();
    let mut i = 0;
    while i < line.len() {
        let Some(colon) = line[i..].find(':').map(|p| p + i) else {
            break;
        };
        // digits after the colon
        let mut j = colon + 1;
        while j < bytes.len() && bytes[j].is_ascii_digit() {
            j += 1;
        }
        if j == colon + 1 {
            i = colon + 1;
            continue;
        }
        // path before the colon
        let mut s = colon;
        while s > 0 {
            let b = bytes[s - 1];
            if b.is_ascii_alphanumeric() || matches!(b, b'.' | b'/' | b'_' | b'-') {
                s -= 1;
            } else {
                break;
            }
        }
        let path = &line[s..colon];
        if EXTS.iter().any(|e| path.ends_with(e)) {
            if let Ok(n) = line[colon + 1..j].parse::<usize>() {
                out.push((s, path.to_string(), n));
            }
        }
        i = j.max(colon + 1);
    }
    out
}

/// The `` `identifier` `` **immediately** preceding a citation, in the
/// document's canonical form:
///
/// ```text
/// `run_go_build_once` (`[main]` `build.rs:655-682`)
/// ```
///
/// Adjacency is required. A "nearest identifier anywhere to the left" heuristic
/// mis-associates every citation after the first in the dense changelog rows,
/// and a citation checker that invents failures is worse than one that checks
/// less: a signal nobody trusts is a signal nobody reads. Where no adjacent
/// identifier exists the citation is checked for line existence only.
fn preceding_backticked_ident(head: &str) -> Option<String> {
    // the citation's own opening backtick
    let s = head.strip_suffix('`')?;
    let s = s.trim_end();
    // an optional `[tag]` between the identifier and the citation
    let s = ["main", "bdb", "p5e", "exp"]
        .iter()
        .find_map(|t| s.strip_suffix(&format!("`[{t}]`")))
        .unwrap_or(s);
    let s = s.trim_end_matches([' ', '(', '\t']);
    let s = s.strip_suffix('`')?;
    let open = s.rfind('`')?;
    let inner = &s[open + 1..];
    let is_ident = !inner.is_empty()
        && inner
            .bytes()
            .all(|b| b.is_ascii_alphanumeric() || b == b'_')
        && !inner.bytes().all(|b| b.is_ascii_digit());
    if is_ident {
        Some(inner.to_string())
    } else {
        None
    }
}

/// Returns `(findings, warnings, total)`.
///
/// Severity follows §9.6: **a missing token is a FAIL; a moved line is a
/// warning.** Two cases §9.6 does not name are handled conservatively:
/// an untagged citation is a FAIL (Citation-provenance rule 3 — "a citation
/// without a tag is a defect, not a detail"), and a citation whose tagged
/// branch is not present in this clone is a warning, because absence of a
/// reference branch is a property of the checkout, not of the document.
fn check_citations(ctx: &Ctx) -> (Vec<String>, Vec<String>, usize) {
    let doc_rel = "docs/bluedb/v2-architecture.md";
    let Some(doc) = ctx.read(doc_rel) else {
        return (
            vec![format!("{doc_rel} is missing — G0.7 cannot check citations")],
            vec![],
            0,
        );
    };

    let cites = parse_citations(&doc);
    let mut findings = Vec::new();
    let mut warnings = Vec::new();
    let mut branch_cache: BTreeMap<String, bool> = BTreeMap::new();
    let mut listing_cache: BTreeMap<String, Vec<String>> = BTreeMap::new();

    for c in &cites {
        let Some(tag) = c.tag.as_deref() else {
            findings.push(format!(
                "{doc_rel}:{}: citation `{}:{}` carries no [main]/[bdb]/[p5e]/[exp] tag",
                c.line_no, c.path, c.line
            ));
            continue;
        };
        let Some(branch) = tag_branch(tag) else {
            findings.push(format!(
                "{doc_rel}:{}: unknown citation tag [{tag}]",
                c.line_no
            ));
            continue;
        };

        if branch != "HEAD" {
            let known = *branch_cache
                .entry(branch.to_string())
                .or_insert_with(|| git_rev_exists(ctx.root(), branch));
            if !known {
                warnings.push(format!(
                    "{doc_rel}:{}: [{tag}] branch `{branch}` is not present in this clone — `{}:{}` unresolvable here",
                    c.line_no, c.path, c.line
                ));
                continue;
            }
        }

        let Some((resolved_path, text)) =
            resolve_cited_file(ctx, branch, tag, &c.path, c.token.as_deref(), &mut listing_cache)
        else {
            findings.push(format!(
                "{doc_rel}:{}: `{}:{}` [{tag}] does not resolve to a file on `{branch}`",
                c.line_no, c.path, c.line
            ));
            continue;
        };

        let n_lines = text.lines().count();
        if let Some(tok) = &c.token {
            if !text.contains(tok.as_str()) {
                findings.push(format!(
                    "{doc_rel}:{}: `{}:{}` [{tag}] no longer contains the cited token `{tok}` (resolved {resolved_path})",
                    c.line_no, c.path, c.line
                ));
                continue;
            }
            let at_line = text
                .lines()
                .nth(c.line.saturating_sub(1))
                .map(|l| l.contains(tok.as_str()))
                .unwrap_or(false);
            if !at_line {
                warnings.push(format!(
                    "{doc_rel}:{}: `{}:{}` [{tag}] — `{tok}` moved (still present in {resolved_path})",
                    c.line_no, c.path, c.line
                ));
            }
        } else if c.line > n_lines {
            findings.push(format!(
                "{doc_rel}:{}: `{}:{}` [{tag}] points past EOF ({resolved_path} has {n_lines} lines)",
                c.line_no, c.path, c.line
            ));
        }
    }

    (findings, warnings, cites.len())
}

fn git_rev_exists(root: &Path, rev: &str) -> bool {
    std::process::Command::new("git")
        .args(["rev-parse", "--verify", "--quiet", rev])
        .current_dir(root)
        .output()
        .map(|o| o.status.success())
        .unwrap_or(false)
}

/// Subtrees a tag's citations are expected to live in, most specific first,
/// used to break basename ambiguity. `[bdb]`'s engine path is
/// `runtime-go/bluedb/…`, never `runtime-go/rt/bluedb/…` (Citation provenance
/// rule 2), so the engine subtree wins over `rt` for a `[bdb]` citation.
fn tag_roots(tag: &str) -> &'static [&'static str] {
    match tag {
        "bdb" => &["runtime-go/bluedb/", "runtime-go/rt/", "runtime-go/"],
        "p5e" | "exp" => &["runtime-go/rt/", "runtime-go/"],
        _ => &[],
    }
}

fn branch_listing(ctx: &Ctx, branch: &str, cache: &mut BTreeMap<String, Vec<String>>) -> Vec<String> {
    if let Some(v) = cache.get(branch) {
        return v.clone();
    }
    let files = std::process::Command::new("git")
        .args(["ls-tree", "-r", "--name-only", branch])
        .current_dir(ctx.root())
        .output()
        .ok()
        .filter(|o| o.status.success())
        .map(|o| {
            String::from_utf8_lossy(&o.stdout)
                .lines()
                .map(|s| s.to_string())
                .collect::<Vec<_>>()
        })
        .unwrap_or_default();
    cache.insert(branch.to_string(), files.clone());
    files
}

/// Resolve a cited path against a branch.
///
/// The document cites a mix of full repo-relative paths (`runtime-go/rt/live.go`),
/// partial paths (`rt/jobs/sqlite_store.go`) and bare basenames
/// (`committer.go`). All three are accepted: the citation must **suffix-match
/// exactly one path** on the tagged branch, with ties broken in favour of the
/// tag's canonical subtree. An ambiguity that survives that is not resolvable,
/// and saying so is the point — an ambiguous citation cannot be checked.
fn resolve_cited_file(
    ctx: &Ctx,
    branch: &str,
    tag: &str,
    path: &str,
    token: Option<&str>,
    cache: &mut BTreeMap<String, Vec<String>>,
) -> Option<(String, String)> {
    let files = branch_listing(ctx, branch, cache);

    let mut matches: Vec<String> = files
        .iter()
        .filter(|p| *p == path || p.ends_with(&format!("/{path}")))
        .cloned()
        .collect();

    // 1. the tag's canonical subtrees, most specific first
    if matches.len() > 1 {
        for root in tag_roots(tag) {
            let narrowed: Vec<String> = matches
                .iter()
                .filter(|p| p.starts_with(root))
                .cloned()
                .collect();
            if narrowed.len() == 1 {
                matches = narrowed;
                break;
            }
            if narrowed.len() > 1 {
                matches = narrowed;
            }
        }
    }

    // 2. the cited token itself — `run_go_build_once` picks
    //    `rust/crates/project/src/build.rs` out of the three `build.rs` files
    //    without anyone hard-coding which one the document meant.
    if matches.len() > 1 {
        if let Some(tok) = token {
            let narrowed: Vec<String> = matches
                .iter()
                .filter(|p| {
                    git_show(ctx, branch, p)
                        .map(|t| t.contains(tok))
                        .unwrap_or(false)
                })
                .cloned()
                .collect();
            if narrowed.len() == 1 {
                matches = narrowed;
            }
        }
    }

    // 3. shallowest path — `AGENTS.md` cited bare means the repo-root file, not
    //    `templates/AGENTS.md`.
    if matches.len() > 1 {
        if let Some(min) = matches.iter().map(|p| p.matches('/').count()).min() {
            let narrowed: Vec<String> = matches
                .iter()
                .filter(|p| p.matches('/').count() == min)
                .cloned()
                .collect();
            if narrowed.len() == 1 {
                matches = narrowed;
            }
        }
    }

    if matches.len() != 1 {
        return None;
    }
    let cand = matches.remove(0);
    let text = git_show(ctx, branch, &cand)?;
    Some((cand, text))
}

fn git_show(ctx: &Ctx, branch: &str, path: &str) -> Option<String> {
    let out = std::process::Command::new("git")
        .args(["show", &format!("{branch}:{path}")])
        .current_dir(ctx.root())
        .output()
        .ok()?;
    if out.status.success() {
        Some(String::from_utf8_lossy(&out.stdout).to_string())
    } else {
        None
    }
}

