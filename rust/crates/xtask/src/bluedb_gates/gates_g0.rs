/// The gate reads the **snapshot** taken before this run regenerates the file.
/// Checking the file the run is about to write would be a tautology — the class
/// of regression test the mandate calls out by name.
pub fn g0_1_status_generated(ctx: &Ctx) -> GateOutcome {
    let Some(text) = ctx.status_snapshot.as_deref() else {
        return GateOutcome::fail(
            "docs/bluedb/STATUS.md is absent",
            vec!["STATUS.md is generated output and must be committed; run `cargo run -p xtask -- bluedb-gates`".into()],
        );
    };

    let mut findings = Vec::new();

    if !text.contains("<!-- GENERATED by `cargo run -p xtask -- bluedb-gates`. DO NOT EDIT. -->") {
        findings.push("STATUS.md is missing the GENERATED banner".into());
    }

    match status::split_body_and_sha(text) {
        None => findings.push(
            "STATUS.md has no trailing `<!-- body-sha256: … -->` line — hand edits would be undetectable"
                .into(),
        ),
        Some((body, recorded)) => {
            let actual = sha256::hex(body.as_bytes());
            if actual != recorded {
                findings.push(format!(
                    "body-sha256 mismatch: recorded {recorded}, actual {actual} — STATUS.md was hand-edited; regenerate with `cargo run -p xtask -- bluedb-gates`"
                ));
            }
        }
    }

    if findings.is_empty() {
        GateOutcome::pass("STATUS.md carries the generated banner and a matching body-sha256")
    } else {
        GateOutcome::fail("STATUS.md is not trustworthy generated output", findings)
    }
}

