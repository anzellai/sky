// ---------------------------------------------------------------------------
// G0.1 — STATUS.md is generated output
// ---------------------------------------------------------------------------

/// The gate reads the **snapshot** taken before this run regenerates the file.
/// Checking the file the run is about to write would be a tautology — the class
/// of regression test the mandate calls out by name.
pub fn g0_1_status_generated(ctx: &Ctx) -> GateOutcome {
    let Some(text) = ctx.status_snapshot.as_deref() else {
        return GateOutcome::fail(
            "docs/bluedb/STATUS.md is absent",
            vec!["STATUS.md is generated output and must be committed; run `cargo run -p xtask -- bluedb-gates`".into()],
        );
    };

    let mut findings = Vec::new();

    if !text.contains("<!-- GENERATED by `cargo run -p xtask -- bluedb-gates`. DO NOT EDIT. -->") {
        findings.push("STATUS.md is missing the GENERATED banner".into());
    }

    match status::split_body_and_sha(text) {
        None => findings.push(
            "STATUS.md has no trailing `<!-- body-sha256: … -->` line — hand edits would be undetectable"
                .into(),
        ),
        Some((body, recorded)) => {
            let actual = sha256::hex(body.as_bytes());
            if actual != recorded {
                findings.push(format!(
                    "body-sha256 mismatch: recorded {recorded}, actual {actual} — STATUS.md was hand-edited; regenerate with `cargo run -p xtask -- bluedb-gates`"
                ));
            }
        }
    }

    if findings.is_empty() {
        GateOutcome::pass("STATUS.md carries the generated banner and a matching body-sha256")
    } else {
        GateOutcome::fail("STATUS.md is not trustworthy generated output", findings)
    }
}

// ---------------------------------------------------------------------------
// G0.2 — layering
// ---------------------------------------------------------------------------

const GO_MODULE: &str = "sky-app";

/// `rt` must never import `bluedb`; `bluedb` may import only pebble + stdlib.
///
/// The first arm quantifies over `runtime-go/rt/`'s **actual** imports, so it is
/// a live assertion today and its declared mutation turns it red today. The
/// second arm is currently quantified over an empty set (P1 has not landed) and
/// is reported as such rather than counted as evidence.
pub fn g0_2_layering(ctx: &Ctx) -> GateOutcome {
    let mut findings = Vec::new();

    let rt_files = collect_go(&ctx.path("runtime-go/rt"));
    let mut rt_scanned = 0usize;
    for f in &rt_files {
        let Ok(text) = std::fs::read_to_string(f) else {
            continue;
        };
        rt_scanned += 1;
        for (line_no, imp) in go_imports(&text) {
            if imp == format!("{GO_MODULE}/bluedb") || imp.starts_with(&format!("{GO_MODULE}/bluedb/"))
            {
                findings.push(format!(
                    "forbidden edge rt -> bluedb: {}:{} imports {imp}",
                    rel(ctx, f),
                    line_no
                ));
            }
        }
    }

    let bluedb_files = collect_go(&ctx.path("runtime-go/bluedb"));
    for f in &bluedb_files {
        let Ok(text) = std::fs::read_to_string(f) else {
            continue;
        };
        for (line_no, imp) in go_imports(&text) {
            if !is_go_stdlib(&imp) && !is_allowed_bluedb_dep(&imp) {
                findings.push(format!(
                    "forbidden edge bluedb -> {imp}: {}:{} (bluedb may import only pebble + stdlib)",
                    rel(ctx, f),
                    line_no
                ));
            }
        }
    }

    if findings.is_empty() {
        GateOutcome::pass(format!(
            "{rt_scanned} rt files scanned, 0 edges to bluedb; {} bluedb files scanned",
            bluedb_files.len()
        ))
    } else {
        GateOutcome::fail("layering violated", findings)
    }
}

fn is_allowed_bluedb_dep(imp: &str) -> bool {
    imp.starts_with("github.com/cockroachdb/pebble")
        || imp.starts_with("github.com/cockroachdb/errors")
        || imp.starts_with("golang.org/x/")
}

