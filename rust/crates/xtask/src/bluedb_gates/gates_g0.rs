//! The G0.x cross-cutting gates — implementable with zero BlueDB code (§10.1,
//! phase P0).
//!
//! Every body here resolves paths through [`Ctx`] and nothing else. That is the
//! H3 contract: under `--verify-mutations` the `Ctx` root is a scratch git
//! worktree, and a body that reached the developer's tree instead — an absolute
//! path, an inherited `cwd` — would make every mutation report `PROVEN`
//! forever.

