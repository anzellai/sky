//! `docs/bluedb/STATUS.md` — generated output (§9.3).
//!
//! The single mechanical property that closes H2: **the table renders from the
//! [`REGISTRY`], not from the run's results.** Every registered gate appears
//! whether or not it executed, so a gate cannot disappear from the report by
//! not running, and a partial run cannot produce a green-looking file.
//!
//! `--only` never reaches this module (§9.1), and the goal column is computed
//! by [`super::registry::goal_verdict`] — there is no prose verdict anywhere.

use std::collections::BTreeMap;

use super::registry::{GateState, GoalVerdict, Tier};
use super::sha256;
use super::state::ProofOutcome;

pub const STATUS_PATH: &str = "docs/bluedb/STATUS.md";

const BANNER: &str = "<!-- GENERATED by `cargo run -p xtask -- bluedb-gates`. DO NOT EDIT. -->";
const SHA_PREFIX: &str = "<!-- body-sha256: ";

/// Per-gate result as the renderer sees it.
pub struct Row {
    pub id: &'static str,
    pub goal: u8,
    pub title: &'static str,
    pub tier: Tier,
    pub state: GateState,
    pub secs: Option<f64>,
    pub detail: String,
    pub findings: Vec<String>,
    /// Rendered "Mutation proof" cell.
    pub proof: String,
    /// Whether the proof is not known-good (`—`, `UNVERIFIED-SINCE`, …). Feeds
    /// the goal verdict exactly as `NOT RUN` does (MAJOR-17).
    pub proof_unknown: bool,
}

pub struct Header {
    pub commit: String,
    pub ran: String,
    pub host: String,
    pub tier: Tier,
    pub full_tier: Option<(String, String, String)>,
    /// `Some(n)` when HEAD is `n` commits ahead of the recorded full-tier run.
    pub full_tier_behind: Option<usize>,
}

/// Render the whole file. Deterministic: the same registry + rows + header
/// always produce byte-identical output, which is what makes `--check`
/// meaningful.
pub fn render(header: &Header, rows: &[Row]) -> String {
    let mut body = String::new();

    let stale = header.full_tier_behind.map(|n| n > 0).unwrap_or(true);

    body.push_str("\n# BlueDB v2 — STATUS\n\n");

    // --- goal roll-up ----------------------------------------------------
    let mut by_goal: BTreeMap<u8, Vec<&Row>> = BTreeMap::new();
    for r in rows {
        by_goal.entry(r.goal).or_default().push(r);
    }

    let mut unknown_goals: Vec<String> = Vec::new();
    let mut goal_lines: Vec<String> = Vec::new();
    for (goal, grows) in &by_goal {
        let states: Vec<(GateState, bool)> =
            grows.iter().map(|r| (r.state, r.proof_unknown)).collect();
        let verdict = super::registry::goal_verdict(&states);
        if verdict == GoalVerdict::Unknown {
            unknown_goals.push(goal_label_short(*goal));
        }
        let gates = grows
            .iter()
            .map(|r| format!("{}{}", r.state.marker(), r.id))
            .collect::<Vec<_>>()
            .join(" ");
        goal_lines.push(format!(
            "| {} | **{}** | {} |\n",
            goal_label(*goal),
            verdict.label(),
            gates
        ));
    }

    if stale {
        let behind = header
            .full_tier_behind
            .map(|n| format!("{n} commits behind HEAD"))
            .unwrap_or_else(|| "never run".to_string());
        body.push_str(&format!(
            "⚠️  FULL-TIER RESULTS ARE STALE — {behind}. Goals {} render UNKNOWN.\n\
             \x20   Run: cargo run -p xtask -- bluedb-gates --tier=full\n\n",
            if unknown_goals.is_empty() {
                "(none)".to_string()
            } else {
                unknown_goals.join(", ")
            }
        ));
    }

    body.push_str("| Goal | Verdict | Gates |\n|---|---|---|\n");
    for l in &goal_lines {
        body.push_str(l);
    }
    body.push_str("\nLegend: (blank)=PASS  ✗=FAIL  ⊘=NOT RUN  ⊗=UNPROVEN\n\n");

    // --- gate table ------------------------------------------------------
    body.push_str("| Gate | Goal | Title | Verdict | Tier | Time | Mutation proof |\n");
    body.push_str("|---|---|---|---|---|---|---|\n");
    for r in rows {
        let verdict = if r.state == GateState::Pass {
            r.state.label().to_string()
        } else {
            format!("**{}**", r.state.label())
        };
        let time = r
            .secs
            .map(|s| format!("{s:.1}s"))
            .unwrap_or_else(|| "—".to_string());
        body.push_str(&format!(
            "| {} | {} | {} | {} | {} | {} | {} |\n",
            r.id,
            r.goal,
            escape_cell(r.title),
            verdict,
            r.tier.label(),
            time,
            escape_cell(&r.proof)
        ));
    }

    body.push_str(
        "\nThe `Mutation proof` cell reads `PROVEN @ <sha>`: the sha `--verify-mutations` was RUN \
         against. That is necessarily an ANCESTOR of the commit recording it — the run happens, \
         then its transcripts and ledger are committed — so an older sha there is the normal \
         state, not a stale one. `UNVERIFIED-SINCE <sha>` is the stale state: a path the mutation \
         declares as a target changed after the proof was taken.\n",
    );

    // --- per-gate detail, PASS INCLUDED ----------------------------------
    //
    // This section used to be `## Failures` and rendered `detail` only for
    // non-PASS rows. A gate's `detail` is where it records what its TITLE does not
    // cover — G0.5's arm (c) reporting "quantified over an empty set", G0.6's "39
    // not authored yet" — and under the old rule those qualifications were
    // unreachable from the artefact the moment their gate went green. The title
    // is what a compacted session inherits; a qualification that only prints on
    // failure is a qualification that is never read.
    //
    // Rows with nothing to say (a NOT-RUN pending gate whose body returns no
    // detail) are omitted rather than padded, so the section stays readable — but
    // a row is included whenever it is non-PASS OR has anything of its own to
    // report, which is exactly the set that could carry a qualification.
    let detailed: Vec<&Row> = rows
        .iter()
        .filter(|r| r.state != GateState::Pass || !r.detail.is_empty() || !r.findings.is_empty())
        .collect();
    if !detailed.is_empty() {
        body.push_str(
            "\n## Gate detail — in each gate's own words, PASS included\n\n\
             A green row is not the whole verdict. Read the gate's own line below before quoting \
             its title: this is where a PASS records the clause it could not reach, the set it \
             quantified over, or the part of its subject that does not exist yet.\n",
        );
        for r in detailed {
            body.push_str(&format!("### {} — {} [{}]\n", r.id, r.title, r.state.label()));
            if !r.detail.is_empty() {
                body.push_str(&format!("    {}\n", r.detail));
            }
            for f in &r.findings {
                body.push_str(&format!("    {f}\n"));
            }
        }
    }

    // --- assemble --------------------------------------------------------
    let mut out = String::new();
    out.push_str(BANNER);
    out.push('\n');
    out.push_str(&format!(
        "<!-- commit:      {}  ran: {}  host: {}  tier: {} -->\n",
        header.commit,
        header.ran,
        header.host,
        header.tier.label()
    ));
    // WHAT THE STAMPS MEAN, stated in the file itself.
    //
    // `commit:` is HEAD at the moment this file was generated. It is NOT the
    // commit that contains this file, and it cannot be: the content must exist
    // before the commit that carries it, so the sha of that commit is not
    // computable while writing it. The stamp therefore always names an ANCESTOR of
    // the commit you are reading it in — normally the parent. The same is true one
    // level down for `PROVEN @ <sha>` in the table.
    //
    // This is inherent, so it is DESCRIBED rather than "fixed": a reader who does
    // not know it reads an older sha as evidence the file is stale, and a reader
    // who assumes it names the containing commit reads the file as claiming more
    // than it can.
    out.push_str(
        "<!-- stamps:      `commit` is HEAD when this file was GENERATED, and `PROVEN @ <sha>` \
         below is the sha `--verify-mutations` RAN at. Both necessarily name an ANCESTOR of the \
         commit that contains them (content precedes its own commit sha), normally the parent. \
         Staleness is reported explicitly instead: see `full-tier` on the next line and the \
         STALE banner in the body. -->\n",
    );
    match &header.full_tier {
        Some((c, ran, host)) => {
            let mark = match header.full_tier_behind {
                Some(0) | None => String::new(),
                Some(n) => format!("  STALE (HEAD is {n} commits ahead)"),
            };
            out.push_str(&format!(
                "<!-- full-tier:   {c}  ran: {ran}  host: {host}{mark} -->\n"
            ));
        }
        None => out.push_str("<!-- full-tier:   (never run)  STALE -->\n"),
    }
    out.push_str(&body);
    out.push_str(&format!("\n{SHA_PREFIX}{} -->\n", sha256::hex(body.as_bytes())));
    out
}

fn escape_cell(s: &str) -> String {
    s.replace('|', "\\|").replace('\n', " ")
}

fn goal_label(goal: u8) -> String {
    match goal {
        0 => "0 — cross-cutting (RULE ZERO harness)".into(),
        1 => "1 — session-bounded Model state sync".into(),
        2 => "2 — unified store, real SERIALIZABLE".into(),
        3 => "3 — easy + simple".into(),
        4 => "4 — notify clients of changesets".into(),
        5 => "5 — console admin access (read+write)".into(),
        n => format!("{n} — ?"),
    }
}

fn goal_label_short(goal: u8) -> String {
    goal.to_string()
}

/// Split a rendered `STATUS.md` into `(body, recorded-sha)`.
///
/// The body is everything from the first blank line after the header comments
/// through the line before the `body-sha256` trailer — i.e. exactly what
/// [`render`] hashed. Returns `None` when the trailer is absent.
pub fn split_body_and_sha(text: &str) -> Option<(String, String)> {
    let idx = text.rfind(SHA_PREFIX)?;
    let recorded = text[idx + SHA_PREFIX.len()..]
        .split_whitespace()
        .next()?
        .to_string();
    let head = &text[..idx];
    // `render` appends "\n{SHA_PREFIX}…" after the body, so drop that one newline.
    let body = head.strip_suffix('\n').unwrap_or(head);
    // and drop the header comment lines
    let body = body
        .lines()
        .skip_while(|l| l.starts_with("<!--"))
        .collect::<Vec<_>>()
        .join("\n");
    Some((format!("{body}\n").trim_end_matches('\n').to_string() + "\n", recorded))
}

/// Render the "Mutation proof" cell for one gate (§9.4's table + MAJOR-17).
pub fn proof_cell(
    gate_id: &str,
    mutation_ids: &[&str],
    ledger: &BTreeMap<String, (ProofOutcome, String)>,
    moved: &dyn Fn(&str, &str) -> bool,
) -> (String, bool) {
    let canary = gate_id == super::registry::CANARY_ID;
    let mut cells = Vec::new();
    let mut unknown = false;

    for id in mutation_ids {
        match ledger.get(*id) {
            None => {
                cells.push("—".to_string());
                unknown = true;
            }
            Some((ProofOutcome::Proven, sha)) => {
                if moved(id, sha) {
                    cells.push(format!("UNVERIFIED-SINCE {sha}"));
                    unknown = true;
                } else {
                    cells.push(format!("PROVEN @ {sha}"));
                }
            }
            Some((ProofOutcome::Vacuous, sha)) if canary => {
                if moved(id, sha) {
                    cells.push(format!("UNVERIFIED-SINCE {sha}"));
                    unknown = true;
                } else {
                    cells.push("VACUOUS ✔".to_string());
                }
            }
            Some((o, sha)) => {
                // VACUOUS on a non-canary gate, MUTATION-STALE, WRONG-TREE,
                // INCONCLUSIVE-BASELINE-RED — all non-PASS.
                cells.push(format!("{} @ {sha}", o.label()));
                unknown = true;
            }
        }
    }

    (cells.join("; "), unknown)
}

#[cfg(test)]
mod tests {
    use super::super::registry::REGISTRY;
    use super::*;

    fn row(id: &'static str, goal: u8, state: GateState) -> Row {
        Row {
            id,
            goal,
            title: "t",
            tier: Tier::Fast,
            state,
            secs: Some(0.1),
            detail: String::new(),
            findings: vec![],
            proof: "PROVEN @ abc".into(),
            proof_unknown: false,
        }
    }

    fn header() -> Header {
        Header {
            commit: "aaaaaaa".into(),
            ran: "2026-08-09T00:00:00Z".into(),
            host: "darwin/arm64".into(),
            tier: Tier::Fast,
            full_tier: Some(("bbbbbbb".into(), "2026-08-08T00:00:00Z".into(), "linux".into())),
            full_tier_behind: Some(0),
        }
    }

    #[test]
    fn body_sha_round_trips_through_split() {
        let out = render(&header(), &[row("G0.1", 0, GateState::Pass)]);
        let (body, sha) = split_body_and_sha(&out).expect("trailer present");
        assert_eq!(sha256::hex(body.as_bytes()), sha);
    }

    #[test]
    fn a_hand_edit_breaks_the_recorded_sha() {
        let out = render(&header(), &[row("G0.1", 0, GateState::Pass)]);
        let tampered = out.replace("BlueDB v2 — STATUS", "BlueDB v2 — STATUS (all green!)");
        let (body, sha) = split_body_and_sha(&tampered).unwrap();
        assert_ne!(sha256::hex(body.as_bytes()), sha);
    }

    #[test]
    fn a_not_run_gate_renders_its_goal_unknown_not_pass() {
        let out = render(
            &header(),
            &[
                row("G1.1", 1, GateState::Pass),
                row("G1.2", 1, GateState::NotRun),
            ],
        );
        assert!(out.contains("| 1 — session-bounded Model state sync | **UNKNOWN** |"));
        assert!(!out.contains("| 1 — session-bounded Model state sync | **PASS** |"));
    }

    #[test]
    fn every_registered_gate_appears_even_when_none_ran() {
        // The H2 property, asserted directly: render with every gate NOT RUN
        // and confirm the table still enumerates the whole registry.
        let rows: Vec<Row> = REGISTRY
            .iter()
            .map(|g| Row {
                id: g.id,
                goal: g.goal,
                title: g.title,
                tier: g.tier,
                state: GateState::NotRun,
                secs: None,
                detail: String::new(),
                findings: vec![],
                proof: "—".into(),
                proof_unknown: true,
            })
            .collect();
        let out = render(&header(), &rows);
        for g in REGISTRY {
            assert!(out.contains(&format!("| {} |", g.id)), "{} missing", g.id);
        }
        assert!(!out.contains("**PASS**"));
    }

    #[test]
    fn proof_cell_decays_to_unverified_since() {
        let mut ledger = BTreeMap::new();
        ledger.insert("G0.2/m".to_string(), (ProofOutcome::Proven, "abc1234".to_string()));

        let (cell, unknown) = proof_cell("G0.2", &["G0.2/m"], &ledger, &|_, _| false);
        assert_eq!(cell, "PROVEN @ abc1234");
        assert!(!unknown);

        let (cell, unknown) = proof_cell("G0.2", &["G0.2/m"], &ledger, &|_, _| true);
        assert_eq!(cell, "UNVERIFIED-SINCE abc1234");
        assert!(unknown, "an unrevalidated proof must render the goal UNKNOWN");
    }

    #[test]
    fn canary_vacuous_is_the_pass_state_only_for_the_canary() {
        let mut ledger = BTreeMap::new();
        ledger.insert("G0.C/noop".to_string(), (ProofOutcome::Vacuous, "abc".to_string()));
        let (cell, unknown) = proof_cell("G0.C", &["G0.C/noop"], &ledger, &|_, _| false);
        assert_eq!(cell, "VACUOUS ✔");
        assert!(!unknown);

        let mut ledger = BTreeMap::new();
        ledger.insert("G0.2/m".to_string(), (ProofOutcome::Vacuous, "abc".to_string()));
        let (_, unknown) = proof_cell("G0.2", &["G0.2/m"], &ledger, &|_, _| false);
        assert!(unknown, "VACUOUS on a real gate means the gate is a green lie");
    }

    #[test]
    fn missing_proof_is_not_silently_green() {
        let ledger = BTreeMap::new();
        let (cell, unknown) = proof_cell("G0.2", &["G0.2/m"], &ledger, &|_, _| false);
        assert_eq!(cell, "—");
        assert!(unknown);
    }
}
