//! E-5: every stdlib name collision a release introduces is listed, reviewed
//! and printed in the CHANGELOG's Breaking section.
//!
//! WHY. `import A exposing (..)` + `import B exposing (..)` is legal, and an
//! unqualified name both modules export is `[E1012]` at its use. So a name a
//! stdlib module STARTS to export can break a program that compiled with the
//! previous release, with no change on the user's side:
//! `import Std.Html.Attributes exposing (..)` + `import Sky.Core.Json.Decode
//! exposing (..)` + a bare `value` compiled with v0.26.1 and is ambiguous in
//! v0.27.0, where `Json.Decode.value` was added. That break is loud and has a
//! one-line fix, so it is allowed, but only when it is known.
//!
//! The SILENT case is worse. An `exposing (..)` import (the Open layer) beats
//! the ambient Prelude and builtins with no diagnostic
//! (`hir/src/resolve.rs`, `BindLayer`). A new stdlib export equal to an ambient
//! name would change what an old program computes without any error.
//!
//! This test compares the stdlib's exports now with the committed snapshot of
//! the previous release (`hir/data/stdlib-exports-v0.26.1.tsv`, regenerated by
//! `hir/tests/regen-stdlib-exports-snapshot.sh`), for values, types and
//! constructors, and for kernel pseudo-modules (`import Auth exposing (..)`).
//! It fails on a collision not in [`EXPECTED_COLLISIONS`], on a listed one that
//! no longer happens, and on any silent rebinding of an ambient name.

use base::FileId;
use hir::stdlib_history::{parse_export_rows, ExportRow, PREVIOUS_EXPORTS_TSV};
use hir::SourceDb;
use std::collections::{BTreeMap, BTreeSet};
use std::path::{Path, PathBuf};

/// The collisions the current stdlib introduces against the previous release,
