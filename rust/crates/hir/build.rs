//! Generates `STDLIB_MODULES`: the module names of the standard library, read
//! from the `sky-stdlib/` source tree that the compiler embeds (`ffi`'s build
//! script stages the same tree).
//!
//! The checker decides "is this module the stdlib?" from this set, never from
//! a name prefix. A project may define a new module under `Std.` or `Sky.`
//! (`project/src/module_ownership.rs`), and such a module is app code. It may
//! not take an exact stdlib name, and a dependency may not use the two roots
//! at all, so membership in this set is the module's origin.

use std::path::{Path, PathBuf};

fn main() {
    let manifest = PathBuf::from(std::env::var("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR"));
    // rust/crates/hir -> rust/crates -> rust -> <repo root>
    let repo = manifest
        .ancestors()
        .nth(3)
        .expect("hir crate must live at <repo>/rust/crates/hir")
        .to_path_buf();
    let root = repo.join("sky-stdlib");
    let mut names = Vec::new();
    collect(&root, &root, &mut names);
    assert!(
        !names.is_empty(),
        "no stdlib modules under {}: the checker needs the stdlib source set",
        root.display()
    );
    names.sort();
    names.dedup();
    let mut out = String::from(
        "/// The standard-library module names (generated by `hir/build.rs` from\n\
         /// `sky-stdlib/`), sorted for `binary_search`.\n\
         pub const STDLIB_MODULES: &[&str] = &[\n",
    );
    for n in &names {
        out.push_str(&format!("    {n:?},\n"));
    }
    out.push_str("];\n");
    let dest = PathBuf::from(std::env::var("OUT_DIR").expect("OUT_DIR")).join("stdlib_modules.rs");
    if std::fs::read_to_string(&dest).ok().as_deref() != Some(out.as_str()) {
        std::fs::write(&dest, out).expect("write stdlib_modules.rs");
    }
    println!("cargo:rerun-if-changed={}", root.display());
    println!("cargo:rerun-if-changed=build.rs");
}

/// Every `*.sky` file under `dir`, named by its path below `root`
/// (`Std/App.sky` is `Std.App`).
fn collect(root: &Path, dir: &Path, out: &mut Vec<String>) {
    let Ok(rd) = std::fs::read_dir(dir) else {
        return;
    };
    for entry in rd.flatten() {
        let p = entry.path();
        if p.is_dir() {
            collect(root, &p, out);
        } else if p.extension().is_some_and(|e| e == "sky") {
            let rel = p
                .strip_prefix(root)
                .expect("file under root")
                .with_extension("");
            let parts: Vec<String> = rel
                .components()
                .map(|c| c.as_os_str().to_string_lossy().into_owned())
                .collect();
            out.push(parts.join("."));
        }
    }
}
